package dockerweb

import (
	"fmt"
	"strconv"
	"strings"
)

// Server identifies a supported container web server.
type Server string

const (
	ServerNginx  Server = "nginx"
	ServerApache Server = "apache"
)

// HTTPListenPort and HTTPSListenPort default to the production ports.
const (
	defaultHTTPPort  = 80
	defaultHTTPSPort = 443
)

// Validate reports whether the server is supported.
func (s Server) Validate() error {
	switch s {
	case ServerNginx, ServerApache:
		return nil
	default:
		return fmt.Errorf("dockerweb: unsupported server %q", s)
	}
}

// RenderBase renders the full base configuration for a container web server.
// The returned bytes are seeded once as a user-owned base file; later syncs
// never replace an edited base.
func RenderBase(server Server, httpPort, httpsPort int) ([]byte, error) {
	if err := server.Validate(); err != nil {
		return nil, err
	}
	if err := validateListenPorts(httpPort, httpsPort); err != nil {
		return nil, err
	}
	switch server {
	case ServerNginx:
		return nginxBaseConfig(httpPort, httpsPort), nil
	case ServerApache:
		return apacheBaseConfig(httpPort, httpsPort), nil
	default:
		return nil, fmt.Errorf("dockerweb: unsupported server %q", server)
	}
}

func nginxBaseConfig(httpPort, httpsPort int) []byte {
	_ = httpPort
	_ = httpsPort
	return []byte(`# Generated by devstack. Base nginx configuration for the devstack web-server container.
# This file is user-owned after seeding. Devstack never overwrites local edits.
# Site vhosts are generated under conf.d/generated; user includes live under conf.d/custom.

user  nginx;
worker_processes  auto;
error_log  /var/log/nginx/error.log warn;
pid        /var/run/nginx.pid;

events {
    worker_connections  1024;
}

http {
    include       /etc/nginx/mime.types;
    default_type  application/octet-stream;

    log_format  main  '$remote_addr - $remote_user [$time_local] "$request" '
                      '$status $body_bytes_sent "$http_referer" '
                      '"$http_user_agent" "$http_x_forwarded_for"';
    access_log  /var/log/nginx/access.log  main;

    sendfile        on;
    tcp_nopush      on;
    keepalive_timeout  65;
    server_tokens   off;

    gzip  on;
    gzip_types text/plain text/css application/json application/javascript text/xml application/xml image/svg+xml;

    # Default branded 404 for unknown hosts. Seeded by devstack.
    include /etc/nginx/conf.d/00-devstack-default.conf;
    # Managed site and dashboard vhosts. Do not edit generated files directly.
    include /etc/nginx/conf.d/generated/*.conf;
    # User-owned includes. Devstack never rewrites this directory.
    include /etc/nginx/conf.d/custom/*.conf;
}
`)
}

func apacheBaseConfig(httpPort, httpsPort int) []byte {
	var b strings.Builder
	b.WriteString(`# Generated by devstack. Full Apache HTTP Server configuration for the
# devstack web-server container. This file is user-owned after seeding.
# Site vhosts are generated under conf/conf.d/generated; custom includes live in
# conf/conf.d/custom. Devstack never mounts a wrapper image.

ServerRoot "/usr/local/apache2"
ServerName localhost
Listen `)
	b.WriteString(strconv.Itoa(httpPort))
	b.WriteString("\nListen ")
	b.WriteString(strconv.Itoa(httpsPort))
	b.WriteString("\n")
	b.WriteString(`
# The official httpd image ships these modules; no wrapper image is required.
LoadModule mpm_event_module modules/mod_mpm_event.so
LoadModule unixd_module modules/mod_unixd.so
LoadModule authz_core_module modules/mod_authz_core.so
LoadModule authz_host_module modules/mod_authz_host.so
LoadModule dir_module modules/mod_dir.so
LoadModule mime_module modules/mod_mime.so
LoadModule log_config_module modules/mod_log_config.so
LoadModule setenvif_module modules/mod_setenvif.so
LoadModule headers_module modules/mod_headers.so
LoadModule rewrite_module modules/mod_rewrite.so
LoadModule proxy_module modules/mod_proxy.so
LoadModule proxy_http_module modules/mod_proxy_http.so
LoadModule proxy_fcgi_module modules/mod_proxy_fcgi.so
LoadModule proxy_wstunnel_module modules/mod_proxy_wstunnel.so
LoadModule ssl_module modules/mod_ssl.so
LoadModule socache_shmcb_module modules/mod_socache_shmcb.so
LoadModule deflate_module modules/mod_deflate.so

User daemon
Group daemon

ServerAdmin devstack@localhost
DocumentRoot "/usr/local/apache2/htdocs"

<Directory "/usr/local/apache2/htdocs">
    AllowOverride None
    Require all granted
</Directory>

<IfModule mpm_event_module>
    StartServers             2
    MinSpareThreads         25
    MaxSpareThreads         75
    ThreadsPerChild         25
    MaxRequestWorkers      150
    MaxConnectionsPerChild   0
</IfModule>

<IfModule dir_module>
    DirectoryIndex index.html
</IfModule>

<FilesMatch "^\.ht">
    Require all denied
</FilesMatch>

ErrorLog "/usr/local/apache2/logs/error_log"
LogLevel warn
LogFormat "%h %l %u %t \"%r\" %>s %b" common
CustomLog "/usr/local/apache2/logs/access_log" common

TypesConfig conf/mime.types
AddDefaultCharset UTF-8
AddType application/javascript .mjs

SSLSessionCache "shmcb:/usr/local/apache2/logs/ssl_scache(512000)"
SSLSessionCacheTimeout 300

# Default branded 404 vhost sorts first and is seeded by devstack.
IncludeOptional conf/conf.d/*.conf
# Managed site and dashboard vhosts. Do not edit generated files directly.
IncludeOptional conf/conf.d/generated/*.conf
# User-owned includes. Devstack never rewrites this directory.
IncludeOptional conf/conf.d/custom/*.conf
`)
	return []byte(b.String())
}

func validateListenPorts(httpPort, httpsPort int) error {
	for name, port := range map[string]int{"HTTP": httpPort, "HTTPS": httpsPort} {
		if port < 1 || port > 65535 {
			return fmt.Errorf("dockerweb: %s listen port %d must be between 1 and 65535", name, port)
		}
	}
	if httpPort == httpsPort {
		return fmt.Errorf("dockerweb: HTTP and HTTPS listen ports must differ, both are %d", httpPort)
	}
	return nil
}
