package phpfpm

import (
	"bytes"
	"fmt"
	"net"
	"sort"
	"strings"
)

// Render produces one complete php-fpm.conf for cfg. Values are validated
// before rendering; paths and environment values are double-quoted with
// backslashes and quotes escaped.
func Render(cfg Config) ([]byte, error) {
	if err := validateConfig(cfg); err != nil {
		return nil, err
	}

	var out bytes.Buffer
	out.WriteString("; Code generated by devstack. Changes are overwritten on apply.\n")
	if cfg.SiteID != "" {
		fmt.Fprintf(&out, "; site = %s\n", cfg.SiteID)
	}
	if cfg.BuildRoot != "" {
		fmt.Fprintf(&out, "; build root = %s\n", cfg.BuildRoot)
	}
	out.WriteString("\n[global]\n")
	fmt.Fprintf(&out, "pid = %s\n", quote(cfg.PIDFile))
	fmt.Fprintf(&out, "error_log = %s\n", quote(cfg.ErrorLog))
	out.WriteString("daemonize = no\n")
	out.WriteString("log_level = notice\n")

	out.WriteString("\n[www]\n")
	fmt.Fprintf(&out, "listen = %s\n", net.JoinHostPort(cfg.ListenHost, fmt.Sprintf("%d", cfg.ListenPort)))
	if cfg.User != "" {
		fmt.Fprintf(&out, "user = %s\n", cfg.User)
	}
	if cfg.Group != "" {
		fmt.Fprintf(&out, "group = %s\n", cfg.Group)
	}
	out.WriteString("pm = dynamic\n")
	out.WriteString("pm.max_children = 5\n")
	out.WriteString("pm.start_servers = 2\n")
	out.WriteString("pm.min_spare_servers = 1\n")
	out.WriteString("pm.max_spare_servers = 3\n")
	out.WriteString("catch_workers_output = yes\n")
	out.WriteString("clear_env = no\n")
	fmt.Fprintf(&out, "chdir = %s\n", quote(cfg.DocumentRoot))
	out.WriteString("security.limit_extensions = .php\n")

	if len(cfg.Env) > 0 {
		keys := make([]string, 0, len(cfg.Env))
		for key := range cfg.Env {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		for _, key := range keys {
			fmt.Fprintf(&out, "env[%s] = %s\n", key, quote(cfg.Env[key]))
		}
	}
	return out.Bytes(), nil
}

// quote renders a php-fpm double-quoted string. Backslashes and double quotes
// are escaped; control characters were rejected by validation.
func quote(value string) string {
	var builder strings.Builder
	builder.Grow(len(value) + 2)
	builder.WriteByte('"')
	for _, r := range value {
		switch r {
		case '\\', '"':
			builder.WriteByte('\\')
			builder.WriteRune(r)
		default:
			builder.WriteRune(r)
		}
	}
	builder.WriteByte('"')
	return builder.String()
}
