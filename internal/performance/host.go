package performance

import "bytes"

// Validate checks the allowlisted host tuning values. It is used by the
// privileged helper before it renders and writes the fixed sysctl/limits
// files.
func (h HostValues) Validate() error { return h.validate() }

// RenderHostSysctl renders only the allowlisted sysctl keys from validated
// host metadata. It never writes a file.
func RenderHostSysctl(profile Profile, host HostValues) ([]byte, error) {
	if err := profile.Validate(); err != nil {
		return nil, err
	}
	if err := host.Validate(); err != nil {
		return nil, err
	}
	var out bytes.Buffer
	writeHostHeader(&out, profile, "sysctl")
	out.WriteString("# Apply with: sysctl --system ; remove with: devstack performance reset\n")
	writeSysctlValues(&out, host)
	return out.Bytes(), nil
}

// RenderHostLimits renders only the allowlisted nofile limits from validated
// host metadata. It never writes a file.
func RenderHostLimits(profile Profile, host HostValues) ([]byte, error) {
	if err := profile.Validate(); err != nil {
		return nil, err
	}
	if err := host.Validate(); err != nil {
		return nil, err
	}
	var out bytes.Buffer
	writeHostHeader(&out, profile, "limits")
	identities := make([]string, 0, 2)
	if host.User != "" {
		identities = append(identities, host.User)
	}
	if host.Group != "" {
		identities = append(identities, "@"+host.Group)
	}
	writeLimitsValues(&out, identities, host)
	return out.Bytes(), nil
}

func writeHostHeader(out *bytes.Buffer, profile Profile, kind string) {
	out.WriteString("# Code generated by devstack performance profile ")
	out.WriteString(string(profile))
	out.WriteString(" (")
	out.WriteString(kind)
	out.WriteString("). Do not edit.\n")
}
