// NginxIncludes holds the three managed nginx snippets. Main is included in
// the main context, Events inside the events block, and HTTP inside the http
// block. The snippets never contain block wrappers and never select epoll.
//
// The vhost/listener renderer owns listener syntax: it must set the 80/443
// listen backlog from Host.Somaxconn. This package cannot emit a listener
// directive from an http-context include.
type NginxIncludes struct {
	Main   []byte
	Events []byte
	HTTP   []byte
}

// RenderNginx renders deterministic nginx performance snippets.
func RenderNginx(v Values) (NginxIncludes, error) {
	if err := v.Validate(); err != nil {
		return NginxIncludes{}, err
	}

	var main bytes.Buffer
	writeNginxHeader(&main, v.Profile, "main")
	fmt.Fprintf(&main, "worker_processes %d;\n", v.Nginx.Workers)
	fmt.Fprintf(&main, "worker_rlimit_nofile %d;\n", v.Nginx.WorkerRLimitNoFile)
	main.WriteString("worker_cpu_affinity auto;\n")
	main.WriteString("pcre_jit on;\n")

	var events bytes.Buffer
	writeNginxHeader(&events, v.Profile, "events")
	fmt.Fprintf(&events, "worker_connections %d;\n", v.Nginx.WorkerConnections)
	events.WriteString("multi_accept on;\n")

	var http bytes.Buffer
	writeNginxHeader(&http, v.Profile, "http")
	http.WriteString("sendfile on;\n")
	http.WriteString("tcp_nopush on;\n")
	http.WriteString("tcp_nodelay on;\n")
	fmt.Fprintf(&http, "keepalive_timeout %ds;\n", v.Nginx.KeepaliveTimeoutSeconds)
	fmt.Fprintf(&http, "keepalive_requests %d;\n", v.Nginx.KeepaliveRequests)
	fmt.Fprintf(&http, "open_file_cache max=%d inactive=60s;\n", v.Nginx.OpenFileCacheMax)
	http.WriteString("open_file_cache_valid 30s;\n")
	http.WriteString("open_file_cache_min_uses 2;\n")
	http.WriteString("open_file_cache_errors on;\n")
	if v.Nginx.Gzip {
		http.WriteString("gzip on;\n")
		fmt.Fprintf(&http, "gzip_comp_level %d;\n", v.Nginx.GzipCompLevel)
		http.WriteString("gzip_min_length 1024;\n")
		http.WriteString("gzip_types text/plain text/css application/json application/javascript application/xml image/svg+xml;\n")
	} else {
		http.WriteString("gzip off;\n")
	}

	return NginxIncludes{
		Main:   main.Bytes(),
		Events: events.Bytes(),
		HTTP:   http.Bytes(),
	}, nil
}

func writeNginxHeader(out *bytes.Buffer, profile Profile, context string) {
	fmt.Fprintf(out, "# Code generated by devstack performance profile %q (%s context). Do not edit.\n", profile, context)
}

// RenderApache renders a deterministic MPM event tuning file for the
// server-level Apache configuration. The base configuration must include it
// and must not repeat the same directives inline.
func RenderApache(v Values) ([]byte, error) {
	if err := v.Validate(); err != nil {
		return nil, err
	}

	var out bytes.Buffer
	fmt.Fprintf(&out, "# Code generated by devstack performance profile %q. Do not edit.\n", v.Profile)
	out.WriteString("# MPM event is the only supported multi-processing module.\n\n")
	out.WriteString("<IfModule mpm_event_module>\n")
	fmt.Fprintf(&out, "    ThreadsPerChild %d\n", v.Apache.ThreadsPerChild)
	fmt.Fprintf(&out, "    ServerLimit %d\n", v.Apache.ServerLimit)
	fmt.Fprintf(&out, "    MaxRequestWorkers %d\n", v.Apache.MaxRequestWorkers)
	fmt.Fprintf(&out, "    StartServers %d\n", v.Apache.StartServers)
	fmt.Fprintf(&out, "    MinSpareThreads %d\n", v.Apache.MinSpareThreads)
	fmt.Fprintf(&out, "    MaxSpareThreads %d\n", v.Apache.MaxSpareThreads)
	fmt.Fprintf(&out, "    AsyncRequestWorkerFactor %d\n", v.Apache.AsyncRequestWorkerFactor)
	fmt.Fprintf(&out, "    MaxConnectionsPerChild %d\n", v.Apache.MaxConnectionsPerChild)
	out.WriteString("</IfModule>\n\n")
	if v.Apache.KeepAlive {
		out.WriteString("KeepAlive On\n")
	} else {
		out.WriteString("KeepAlive Off\n")
	}
	fmt.Fprintf(&out, "MaxKeepAliveRequests %d\n", v.Apache.MaxKeepAliveRequests)
	fmt.Fprintf(&out, "KeepAliveTimeout %d\n", v.Apache.KeepAliveTimeoutSeconds)
	out.WriteString("HostnameLookups Off\n")
	out.WriteString("EnableSendfile On\n")
	fmt.Fprintf(&out, "ListenBacklog %d\n", v.Apache.ListenBacklog)
	return out.Bytes(), nil
}

// RenderPHPPool renders the per-site php-fpm sizing preview. It intentionally
// does not emit a [www] section: the daemon persists these values on the site
// and applies them to the existing pool through validate/swap, so including the
// fragment cannot create a second pool. OPcache and realpath-cache settings are
// rendered separately by RenderPHPINI because they are PHP_INI_SYSTEM values,
// not pool overrides.
func RenderPHPPool(v Values, siteID string) ([]byte, error) {
	if err := v.Validate(); err != nil {
		return nil, err
	}

	var site *PHPSite
	for i := range v.PHP.Sites {
		if v.PHP.Sites[i].SiteID == siteID {
			site = &v.PHP.Sites[i]
			break
		}
	}
	if site == nil {
		return nil, invalid("php site", "%q is not in the computed profile", siteID)
	}

	var out bytes.Buffer
	fmt.Fprintf(&out, "; Code generated by devstack performance profile %q. Do not edit.\n", v.Profile)
	fmt.Fprintf(&out, "; profile = %s\n", v.Profile)
	fmt.Fprintf(&out, "; site = %s\n", site.SiteID)
	out.WriteString("; Preview only. Apply the profile to persist these values and update the live pool.\n")
	out.WriteString("; This file is a fragment; it must not be included as a second [www] pool.\n\n")
	fmt.Fprintf(&out, "pm = %s\n", v.PHP.Mode)
	fmt.Fprintf(&out, "pm.max_children = %d\n", site.MaxChildren)
	if v.PHP.Mode == PHPModeDynamic {
		fmt.Fprintf(&out, "pm.start_servers = %d\n", site.StartServers)
		fmt.Fprintf(&out, "pm.min_spare_servers = %d\n", site.MinSpareServers)
		fmt.Fprintf(&out, "pm.max_spare_servers = %d\n", site.MaxSpareServers)
	}
	fmt.Fprintf(&out, "listen.backlog = %d\n", v.PHP.ListenBacklog)
	out.WriteString("; OPcache and realpath cache are PHP_INI_SYSTEM settings; generate them\n")
	out.WriteString("; into the per-site php.ini with RenderPHPINI, not as FPM pool overrides.\n")
	return out.Bytes(), nil
}

// RenderPHPINI renders the OPcache and realpath-cache directives that belong
// in the per-site php.ini. These are PHP_INI_SYSTEM settings and must not be
// shipped as PHP-FPM pool overrides.
func RenderPHPINI(v Values) ([]byte, error) {
	if err := v.Validate(); err != nil {
		return nil, err
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "; Code generated by devstack performance profile %q. Do not edit.\n", v.Profile)
	fmt.Fprintf(&out, "; profile = %s\n", v.Profile)
	out.WriteString("; Merge into the per-site php.ini; these are PHP_INI_SYSTEM settings.\n\n")
	if v.PHP.Opcache.Enabled {
		out.WriteString("opcache.enable = 1\n")
	} else {
		out.WriteString("opcache.enable = 0\n")
	}
	fmt.Fprintf(&out, "opcache.memory_consumption = %d\n", v.PHP.Opcache.MemoryMB)
	fmt.Fprintf(&out, "opcache.interned_strings_buffer = %d\n", v.PHP.Opcache.InternedStringsMB)
	fmt.Fprintf(&out, "opcache.max_accelerated_files = %d\n", v.PHP.Opcache.MaxAcceleratedFiles)
	if v.PHP.Opcache.ValidateTimestamps {
		out.WriteString("opcache.validate_timestamps = 1\n")
	} else {
		out.WriteString("opcache.validate_timestamps = 0\n")
		out.WriteString("; opcache.validate_timestamps=0 requires an explicit cache reset after code changes.\n")
	}
	fmt.Fprintf(&out, "opcache.revalidate_freq = %d\n", v.PHP.Opcache.RevalidateFreqSeconds)
	fmt.Fprintf(&out, "realpath_cache_size = %dK\n", v.PHP.RealpathCacheSizeKB)
	fmt.Fprintf(&out, "realpath_cache_ttl = %d\n", v.PHP.RealpathCacheTTLSeconds)
	return out.Bytes(), nil
}

// RenderSysctl renders only the allowlisted sysctl keys, in stable order.
func RenderSysctl(v Values) ([]byte, error) {
	if err := v.Validate(); err != nil {
		return nil, err
	}
	var out bytes.Buffer
	writeHostHeader(&out, v.Profile, "sysctl")
	out.WriteString("# Apply with: sysctl --system ; remove with: devstack performance reset\n")
	writeSysctlValues(&out, v.Host)
	return out.Bytes(), nil
}

func writeSysctlValues(out *bytes.Buffer, host HostValues) {
	out.WriteString("fs.file-max = ")
	out.WriteString(intString(host.FileMax))
	out.WriteString("\nnet.core.somaxconn = ")
	out.WriteString(intString(uint64(host.Somaxconn)))
	out.WriteString("\nnet.core.netdev_max_backlog = ")
	out.WriteString(intString(uint64(host.NetdevMaxBacklog)))
	out.WriteString("\nnet.ipv4.ip_local_port_range = ")
	out.WriteString(intString(uint64(host.IPLocalPortRange.Min)))
	out.WriteString(" ")
	out.WriteString(intString(uint64(host.IPLocalPortRange.Max)))
	out.WriteString("\n")
}

// RenderLimits renders the allowlisted nofile limits for the supplied
// user/group, or machine-wide when neither is supplied.
func RenderLimits(v Values) ([]byte, error) {
	if err := v.Validate(); err != nil {
		return nil, err
	}
	var out bytes.Buffer
	writeHostHeader(&out, v.Profile, "limits")
	identities := make([]string, 0, 2)
	if v.Host.User != "" {
		identities = append(identities, v.Host.User)
	}
	if v.Host.Group != "" {
		identities = append(identities, "@"+v.Host.Group)
	}
	writeLimitsValues(&out, identities, v.Host)
	return out.Bytes(), nil
}

func writeLimitsValues(out *bytes.Buffer, identities []string, host HostValues) {
	if len(identities) == 0 {
		identities = append(identities, "*")
		out.WriteString("# No user/group supplied: limits apply machine-wide.\n")
		out.WriteString("# Devstack services and containers receive matching ulimits.\n")
	} else {
		out.WriteString("# Applies to the supplied devstack user/group.\n")
	}
	for _, identity := range identities {
		out.WriteString(identity)
		out.WriteString(" soft nofile ")
		out.WriteString(intString(host.NoFileSoft))
		out.WriteString("\n")
		out.WriteString(identity)
		out.WriteString(" hard nofile ")
		out.WriteString(intString(host.NoFileHard))
		out.WriteString("\n")
	}
}

func intString(value uint64) string { return strconv.FormatUint(value, 10) }
