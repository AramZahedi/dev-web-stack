var releaseNamePattern = regexp.MustCompile(`^[0-9]{8}T[0-9]{6}Z(?:-[0-9]+)?$`)

// vhostState is the persisted helper-owned vhost state. The configured state
// file is root-only and rewritten atomically after every change.
type vhostState struct {
	Mode                  string    `json:"mode"`
	Server                string    `json:"server,omitempty"`
	ServerVersion         string    `json:"server_version,omitempty"`
	BridgePath            string    `json:"bridge_path,omitempty"`
	BridgeHash            string    `json:"bridge_hash,omitempty"`
	CurrentRelease        string    `json:"current_release,omitempty"`
	ReloadService         string    `json:"reload_service,omitempty"`
	ConfigOK              bool      `json:"config_ok"`
	LastError             string    `json:"last_error,omitempty"`
	LastSync              time.Time `json:"last_sync"`
	DefaultServerConflict bool      `json:"default_server_conflict,omitempty"`
	TLSOwners             []string  `json:"tls_owners,omitempty"`
}

func builtinState() vhostState {
	return vhostState{Mode: vhostModeBuiltin, ConfigOK: true}
}

// VhostManager installs rendered vhosts, TLS files, and one bridge include for
// an external nginx or Apache server. It never accepts config text, commands,
// or arbitrary paths from the caller; every path is validated first.
type VhostManager struct {
	root      string
	statePath string
	authority *Authority
	runner    CommandRunner
	logger    *slog.Logger

	// TLSDir is the directory receiving <owner>.crt and <owner>.key files. It
	// defaults to <root>/tls when empty.
	TLSDir string
	// HTTPListenPort and HTTPSListenPort are the listen ports rendered into
	// vhosts. Zero selects the production defaults, 80 and 443. Only tests set
	// high ports so a real server can run unprivileged.
	HTTPListenPort  int
	HTTPSListenPort int
	// NginxIncludeDir and ApacheIncludeDir override the auto-detected include
	// directories. Explicit values skip main-config verification.
	NginxIncludeDir  string
	ApacheIncludeDir string
	// Forwarders enables or disables the built-in privileged forwarders. It is
	// wired to the helper server in production and replaced in tests.
	Forwarders func(context.Context, bool) error

	now             func() time.Time
	syncMu          sync.Mutex
	nginxCandidates func(prefix, confPath string) []includeCandidate
}

// NewVhostManager returns a manager rooted at root, the vhost tree containing
// <server>/releases. statePath is the JSON state file.
func NewVhostManager(root, statePath string, authority *Authority, runner CommandRunner, logger *slog.Logger) *VhostManager {
	if logger == nil {
		logger = slog.Default()
	}
	if runner == nil {
		runner = execRunner{}
	}
	root = filepath.Clean(root)
	return &VhostManager{
		root:      root,
		statePath: statePath,
		authority: authority,
		runner:    runner,
		logger:    logger,
		TLSDir:    filepath.Join(root, "tls"),
		now:       time.Now,
	}
}

func (m *VhostManager) tlsDir() string {
	if m.TLSDir != "" {
		return m.TLSDir
	}
	return filepath.Join(m.root, "tls")
}

func (m *VhostManager) serverTree(server string) string {
	return filepath.Join(m.root, server)
}

func (m *VhostManager) currentTime() time.Time {
	if m.now != nil {
		return m.now().UTC()
	}
	return time.Now().UTC()
}

// Status returns the persisted state plus live service state. The only command
// it runs is a fixed `systemctl is-active` probe for the external server.
func (m *VhostManager) Status(ctx context.Context) (helperproto.VhostStatusResponse, error) {
	if err := ctx.Err(); err != nil {
		return helperproto.VhostStatusResponse{}, err
	}
	state, err := m.readState()
	if err != nil {
		return helperproto.VhostStatusResponse{}, fmt.Errorf("%w: read vhost state: %v", helperproto.ErrVhostSyncFailed, err)
	}
	status := m.statusFromState(state)
	status.ServiceActive = m.serviceActive(ctx, state)
	return status, nil
}

// serviceActive asks systemd whether the external server is running. A missing
// systemd, inactive unit, or probe error all report false; Doctor turns that
// into an actionable check rather than failing the status call.
func (m *VhostManager) serviceActive(ctx context.Context, state vhostState) bool {
	if state.Mode != vhostModeNginx && state.Mode != vhostModeApache {
		return false
	}
	service := state.ReloadService
	if service == "" {
		if state.Mode == vhostModeNginx {
			service = "nginx"
		} else {
			service = "apache2"
		}
	}
	out, err := m.runner.Run(ctx, "systemctl", "is-active", service)
	if err != nil {
		return false
	}
	return strings.TrimSpace(string(out)) == "active"
}

func (m *VhostManager) statusFromState(state vhostState) helperproto.VhostStatusResponse {
	includePresent := false
	if state.BridgePath != "" {
		if _, err := os.Stat(state.BridgePath); err == nil {
			includePresent = true
		}
	}
	dirMode, files := m.tlsMetadata()
	return helperproto.VhostStatusResponse{
		Mode:                  state.Mode,
		Server:                state.Server,
		ServerVersion:         state.ServerVersion,
		BridgePath:            state.BridgePath,
		IncludePresent:        includePresent,
		CurrentRelease:        state.CurrentRelease,
		ConfigOK:              state.ConfigOK,
		LastError:             state.LastError,
		LastSync:              state.LastSync,
		DefaultServerConflict: state.DefaultServerConflict,
		TLSDir:                m.tlsDir(),
		TLSDirMode:            dirMode,
		TLSFiles:              files,
	}
}

// tlsMetadata reports the TLS directory mode and entry metadata without ever
// opening a key or certificate. The helper runs as root, so this is the only
// safe way for the unprivileged daemon to inspect /etc/devstack/tls.
func (m *VhostManager) tlsMetadata() (uint32, []helperproto.VhostTLSFile) {
	dir := m.tlsDir()
	info, err := os.Lstat(dir)
	if err != nil || !info.IsDir() {
		return 0, nil
	}
	dirMode := uint32(info.Mode().Perm())
	entries, err := os.ReadDir(dir)
	if err != nil {
		return dirMode, nil
	}
	files := make([]helperproto.VhostTLSFile, 0, len(entries))
	for _, entry := range entries {
		entryInfo, err := entry.Info()
		if err != nil {
			continue
		}
		files = append(files, helperproto.VhostTLSFile{
			Name:    entry.Name(),
			Mode:    uint32(entryInfo.Mode().Perm()),
			Regular: entryInfo.Mode().IsRegular(),
		})
	}
	sort.Slice(files, func(i, j int) bool { return files[i].Name < files[j].Name })
	return dirMode, files
}

func (m *VhostManager) readState() (vhostState, error) {
	data, err := os.ReadFile(m.statePath)
	switch {
	case err == nil:
	case errors.Is(err, fs.ErrNotExist):
		return builtinState(), nil
	default:
		return vhostState{}, err
	}
	var state vhostState
	if err := json.Unmarshal(data, &state); err != nil {
		return vhostState{}, fmt.Errorf("parse %s: %w", m.statePath, err)
	}
	if state.Mode == "" {
		state.Mode = vhostModeBuiltin
	}
	return state, nil
}

func (m *VhostManager) writeState(state vhostState) error {
	if state.Mode == "" {
		state.Mode = vhostModeBuiltin
	}
	data, err := json.Marshal(state)
	if err != nil {
		return err
	}
	dir := filepath.Dir(m.statePath)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return fmt.Errorf("create state directory %s: %w", dir, err)
	}
	if err := writeAtomicFile(m.statePath, data, 0o600); err != nil {
		return fmt.Errorf("write vhost state: %w", err)
	}
	return nil
}

// persistedMode reports the mode recorded on disk, or builtin when no state
// exists. It is used to avoid rebinding 80/443 under nginx/Apache on restart.
func (m *VhostManager) persistedMode() (string, error) {
	state, err := m.readState()
	if err != nil {
		return "", err
	}
	return state.Mode, nil
}

// Sync installs a complete vhost set. Only one sync or mode switch may run at a
// time; a concurrent call returns VHOST_SYNC_BUSY.
func (m *VhostManager) Sync(ctx context.Context, req helperproto.VHostSyncRequest) (helperproto.VhostStatusResponse, error) {
	if !m.syncMu.TryLock() {
		return helperproto.VhostStatusResponse{}, fmt.Errorf("%w: another vhost sync or mode switch is running", helperproto.ErrVhostSyncBusy)
	}
	defer m.syncMu.Unlock()
	return m.syncLocked(ctx, req)
}

// SetMode switches the serving mode. builtin ignores req and restores the
// privileged forwarders; nginx and apache require a complete sync request.
func (m *VhostManager) SetMode(ctx context.Context, mode string, req helperproto.VHostSyncRequest) (helperproto.VhostStatusResponse, error) {
	if !m.syncMu.TryLock() {
		return helperproto.VhostStatusResponse{}, fmt.Errorf("%w: another vhost sync or mode switch is running", helperproto.ErrVhostSyncBusy)
	}
	defer m.syncMu.Unlock()

	mode = strings.TrimSpace(mode)
	switch mode {
	case vhostModeBuiltin, vhostModeNginx, vhostModeApache:
	default:
		return helperproto.VhostStatusResponse{}, fmt.Errorf("%w: unsupported serving mode %q", helperproto.ErrInvalidRequest, mode)
	}
	state, err := m.readState()
	if err != nil {
		return helperproto.VhostStatusResponse{}, fmt.Errorf("%w: read vhost state: %v", helperproto.ErrVhostSyncFailed, err)
	}
	if state.Mode == "" {
		state.Mode = vhostModeBuiltin
	}

	if mode == vhostModeBuiltin {
		return m.setBuiltinLocked(ctx, state)
	}
	if state.Mode == vhostModeBuiltin {
		return m.enableExternalLocked(ctx, state, mode, req)
	}
	return m.switchExternalLocked(ctx, state, mode, req)
}

// Remove deletes only the helper-owned bridge, releases, and TLS files, reloads
// the previous server, restores builtin forwarders, and persists builtin state.
func (m *VhostManager) Remove(ctx context.Context) error {
	if !m.syncMu.TryLock() {
		return fmt.Errorf("%w: another vhost sync or mode switch is running", helperproto.ErrVhostSyncBusy)
	}
	defer m.syncMu.Unlock()
	return m.removeLocked(ctx)
}

func (m *VhostManager) enableExternalLocked(ctx context.Context, state vhostState, mode string, req helperproto.VHostSyncRequest) (helperproto.VhostStatusResponse, error) {
	if err := m.setForwarders(ctx, false); err != nil {
		return helperproto.VhostStatusResponse{}, fmt.Errorf("%w: disable built-in forwarders: %v", helperproto.ErrVhostSyncFailed, err)
	}
	req.Mode = mode
	status, err := m.syncLocked(ctx, req)
	if err != nil {
		var errs []error
		errs = append(errs, err)
		if ferr := m.setForwarders(ctx, true); ferr != nil {
			errs = append(errs, fmt.Errorf("restore built-in forwarders: %w", ferr))
		}
		if serr := m.writeState(m.failureState(state, err, false)); serr != nil {
			errs = append(errs, serr)
		}
		return status, errors.Join(errs...)
	}
	return status, nil
}

func (m *VhostManager) switchExternalLocked(ctx context.Context, state vhostState, mode string, req helperproto.VHostSyncRequest) (helperproto.VhostStatusResponse, error) {
	oldServer := state.Server
	if oldServer == "" {
		oldServer = state.Mode
	}
	bridgePath := state.BridgePath
	var bridgeData []byte
	hadBridge := false
	if bridgePath != "" {
		data, err := os.ReadFile(bridgePath)
		switch {
		case err == nil:
			if err := m.verifyBridgeOwnership(state, oldServer, data); err != nil {
				return helperproto.VhostStatusResponse{}, err
			}
			bridgeData = data
			hadBridge = true
		case errors.Is(err, fs.ErrNotExist):
		default:
			return helperproto.VhostStatusResponse{}, fmt.Errorf("%w: read old bridge %s: %v", helperproto.ErrVhostSyncFailed, bridgePath, err)
		}
	}
	if hadBridge {
		if err := os.Remove(bridgePath); err != nil && !errors.Is(err, fs.ErrNotExist) {
			return helperproto.VhostStatusResponse{}, fmt.Errorf("%w: remove old bridge %s: %v", helperproto.ErrVhostSyncFailed, bridgePath, err)
		}
	}
	if hadBridge {
		if err := m.reloadServer(ctx, oldServer, state.ReloadService); err != nil {
			restoreErr := m.restoreBridge(bridgePath, bridgeData)
			reloadErr := m.reloadServer(ctx, oldServer, state.ReloadService)
			var errs []error
			errs = append(errs, err)
			if restoreErr != nil {
				errs = append(errs, fmt.Errorf("restore old bridge: %w", restoreErr))
			}
			if reloadErr != nil {
				errs = append(errs, fmt.Errorf("reload restored old bridge: %w", reloadErr))
			}
			if serr := m.writeState(m.failureState(state, err, state.ConfigOK)); serr != nil {
				errs = append(errs, serr)
			}
			return helperproto.VhostStatusResponse{}, errors.Join(errs...)
		}
	}

	req.Mode = mode
	status, err := m.syncLocked(ctx, req)
	if err != nil {
		var errs []error
		errs = append(errs, err)
		if hadBridge {
			if rerr := m.restoreBridge(bridgePath, bridgeData); rerr != nil {
				errs = append(errs, fmt.Errorf("restore old bridge: %w", rerr))
			}
			if rerr := m.reloadServer(ctx, oldServer, state.ReloadService); rerr != nil {
				errs = append(errs, fmt.Errorf("reload restored old server: %w", rerr))
			}
		}
		if serr := m.writeState(m.failureState(state, err, state.ConfigOK)); serr != nil {
			errs = append(errs, serr)
		}
		return status, errors.Join(errs...)
	}
	return status, nil
}

func (m *VhostManager) setBuiltinLocked(ctx context.Context, state vhostState) (helperproto.VhostStatusResponse, error) {
	if state.Mode == vhostModeBuiltin {
		if err := m.cleanupBuiltinLocked(ctx, state); err != nil {
			return m.statusFromState(state), err
		}
		return m.statusFromState(builtinStateWithTime(m.currentTime())), nil
	}
	builtin, err := m.teardownExternalLocked(ctx, state)
	if err != nil {
		return m.statusFromState(state), err
	}
	return m.statusFromState(builtin), nil
}

// cleanupBuiltinLocked removes any managed leftovers while the persisted mode
// is already builtin. Every removal must succeed before forwarders are started
// and builtin state is rewritten.
func (m *VhostManager) cleanupBuiltinLocked(ctx context.Context, state vhostState) error {
	if state.BridgePath != "" {
		if err := m.removeBridge(state); err != nil {
			return err
		}
	}
	if err := m.removeAllManagedServerFiles(); err != nil {
		return err
	}
	if err := m.removeTLSFiles(state.TLSOwners); err != nil {
		return err
	}
	if err := m.setForwarders(ctx, true); err != nil {
		return fmt.Errorf("%w: enable built-in forwarders: %v", helperproto.ErrVhostSyncFailed, err)
	}
	return m.writeState(builtinStateWithTime(m.currentTime()))
}

func (m *VhostManager) removeLocked(ctx context.Context) error {
	state, err := m.readState()
	if err != nil {
		return fmt.Errorf("%w: read vhost state: %v", helperproto.ErrVhostSyncFailed, err)
	}
	if state.Mode == "" {
		state.Mode = vhostModeBuiltin
	}
	if state.Mode == vhostModeBuiltin {
		return m.cleanupBuiltinLocked(ctx, state)
	}
	_, err = m.teardownExternalLocked(ctx, state)
	return err
}

// teardownExternalLocked stages every managed vhost file, reloads the external
// server without our bridge, enables the builtin forwarders, and only then
// commits builtin state. Any failure before the commit restores the staged
// files and leaves the external mode serving and persisted.
func (m *VhostManager) teardownExternalLocked(ctx context.Context, state vhostState) (vhostState, error) {
	server := state.Server
	if server == "" {
		server = state.Mode
	}
	staged, err := m.stageManagedForTeardown(state)
	if err != nil {
		return state, fmt.Errorf("%w: stage managed files: %w", helperproto.ErrVhostSyncFailed, err)
	}
	rollback := func(cause error) (vhostState, error) {
		var errs []error
		errs = append(errs, cause)
		if rerr := restoreStagedPaths(staged); rerr != nil {
			errs = append(errs, fmt.Errorf("restore managed files: %w", rerr))
		}
		if rerr := m.reloadServer(ctx, server, state.ReloadService); rerr != nil {
			errs = append(errs, fmt.Errorf("reload restored external server: %w", rerr))
		}
		return state, errors.Join(errs...)
	}

	if err := m.reloadServer(ctx, server, state.ReloadService); err != nil {
		return rollback(err)
	}
	if err := m.setForwarders(ctx, true); err != nil {
		return rollback(fmt.Errorf("%w: enable built-in forwarders: %v", helperproto.ErrVhostSyncFailed, err))
	}

	builtin := builtinStateWithTime(m.currentTime())
	if err := m.writeState(builtin); err != nil {
		// The staged files are still intact, so release the privileged ports
		// and restore external serving rather than claiming builtin mode.
		_ = m.setForwarders(ctx, false)
		return rollback(fmt.Errorf("%w: persist builtin vhost state: %v", helperproto.ErrVhostSyncFailed, err))
	}
	if err := cleanupStagedPaths(staged); err != nil {
		builtin.LastError = fmt.Sprintf("builtin forwarders are running, but managed vhost files could not be fully removed: %v", err)
		_ = m.writeState(builtin)
		m.logger.Warn("helper: builtin mode is active with leftover managed vhost files", "error", err)
	} else {
		m.removeEmptyServerDirs()
	}
	return builtin, nil
}

type stagedPath struct {
	original string
	staged   string
}

func (m *VhostManager) stageManagedForTeardown(state vhostState) ([]stagedPath, error) {
	var staged []stagedPath
	add := func(path string) error {
		entry, ok, err := stagePath(path)
		if err != nil {
			return err
		}
		if ok {
			staged = append(staged, entry)
		}
		return nil
	}
	fail := func(err error) ([]stagedPath, error) {
		_ = restoreStagedPaths(staged)
		return nil, err
	}

	if state.BridgePath != "" {
		data, err := os.ReadFile(state.BridgePath)
		switch {
		case err == nil:
			if err := m.verifyBridgeOwnership(state, state.Server, data); err != nil {
				return fail(err)
			}
			if err := add(state.BridgePath); err != nil {
				return fail(err)
			}
		case errors.Is(err, fs.ErrNotExist):
		default:
			return fail(fmt.Errorf("read bridge %s: %w", state.BridgePath, err))
		}
	}

	for _, server := range []string{vhostModeNginx, vhostModeApache} {
		if err := m.stageServerTree(server, add); err != nil {
			return fail(err)
		}
	}

	seen := make(map[string]struct{}, len(state.TLSOwners))
	for _, owner := range state.TLSOwners {
		if !safeOwner(owner) {
			continue
		}
		if _, ok := seen[owner]; ok {
			continue
		}
		seen[owner] = struct{}{}
		for _, ext := range []string{".crt", ".key"} {
			if err := add(filepath.Join(m.tlsDir(), owner+ext)); err != nil {
				return fail(err)
			}
		}
	}
	return staged, nil
}

func (m *VhostManager) stageServerTree(server string, add func(string) error) error {
	serverDir := m.serverTree(server)
	currentPath := filepath.Join(serverDir, "current")
	if info, err := os.Lstat(currentPath); err == nil {
		if info.Mode()&os.ModeSymlink == 0 {
			return fmt.Errorf("refusing to remove non-symlink %s", currentPath)
		}
		if err := add(currentPath); err != nil {
			return fmt.Errorf("stage current link %s: %w", currentPath, err)
		}
	} else if !errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("inspect current link %s: %w", currentPath, err)
	}

	releasesDir := filepath.Join(serverDir, "releases")
	entries, err := os.ReadDir(releasesDir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("read releases %s: %w", releasesDir, err)
	}
	for _, entry := range entries {
		if !entry.IsDir() || !releaseNamePattern.MatchString(entry.Name()) {
			continue
		}
		path := filepath.Join(releasesDir, entry.Name())
		if err := add(path); err != nil {
			return fmt.Errorf("stage release %s: %w", path, err)
		}
	}
	return nil
}

func stagePath(path string) (stagedPath, bool, error) {
	if _, err := os.Lstat(path); err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return stagedPath{}, false, nil
		}
		return stagedPath{}, false, err
	}
	staged := fmt.Sprintf("%s.devstack-stage-%d", path, time.Now().UnixNano())
	if _, err := os.Lstat(staged); err == nil {
		return stagedPath{}, false, fmt.Errorf("stage path %s already exists", staged)
	} else if !errors.Is(err, fs.ErrNotExist) {
		return stagedPath{}, false, err
	}
	if err := os.Rename(path, staged); err != nil {
		return stagedPath{}, false, err
	}
	return stagedPath{original: path, staged: staged}, true, nil
}

func restoreStagedPaths(paths []stagedPath) error {
	var errs []error
	for i := len(paths) - 1; i >= 0; i-- {
		if err := os.Rename(paths[i].staged, paths[i].original); err != nil {
			errs = append(errs, fmt.Errorf("restore %s: %w", paths[i].original, err))
		}
	}
	return errors.Join(errs...)
}

func cleanupStagedPaths(paths []stagedPath) error {
	var errs []error
	for _, entry := range paths {
		if err := os.RemoveAll(entry.staged); err != nil {
			errs = append(errs, fmt.Errorf("remove staged %s: %w", entry.staged, err))
		}
	}
	return errors.Join(errs...)
}

func builtinStateWithTime(now time.Time) vhostState {
	state := builtinState()
	state.LastSync = now
	return state
}

func (m *VhostManager) setForwarders(ctx context.Context, enable bool) error {
	if m.Forwarders == nil {
		return nil
	}
	return m.Forwarders(ctx, enable)
}

func (m *VhostManager) failureState(previous vhostState, cause error, configOK bool) vhostState {
	state := previous
	if state.Mode == "" {
		state.Mode = vhostModeBuiltin
	}
	if state.Mode == vhostModeBuiltin {
		state = builtinState()
	}
	state.ConfigOK = configOK
	state.LastError = scrubVhostOutput([]byte(cause.Error()))
	state.LastSync = m.currentTime()
	return state
}

// syncLocked assumes the caller holds syncMu.
func (m *VhostManager) syncLocked(ctx context.Context, req helperproto.VHostSyncRequest) (helperproto.VhostStatusResponse, error) {
	if err := ctx.Err(); err != nil {
		return helperproto.VhostStatusResponse{}, err
	}
	mode := strings.TrimSpace(req.Mode)
	if mode != vhostModeNginx && mode != vhostModeApache {
		return helperproto.VhostStatusResponse{}, fmt.Errorf("%w: sync mode must be nginx or apache, got %q", helperproto.ErrInvalidRequest, req.Mode)
	}
	server := vhost.Server(mode)

	prepared, err := m.validateSyncRequest(req)
	if err != nil {
		return helperproto.VhostStatusResponse{}, err
	}
	runtime, err := m.detectServer(ctx, mode)
	if err != nil {
		return helperproto.VhostStatusResponse{}, err
	}
	includeDir, err := m.resolveIncludeDir(ctx, mode, runtime)
	if err != nil {
		return helperproto.VhostStatusResponse{}, err
	}
	bridgePath := filepath.Join(includeDir, bridgeFilename)

	// Stock nginx installations often declare their own default_server. Our
	// default 404 vhost must then omit the marker or the config test fails.
	// Detection is best-effort: a failure to inspect existing configs must not
	// stop a sync that would otherwise pass.
	defaultConflict := m.detectDefaultServerConflict(ctx, mode)
	if defaultConflict {
		m.logger.Warn("helper: foreign nginx default_server detected; installing the devstack 404 vhost without the marker")
	}

	files, err := vhost.Render(vhost.Set{
		Server:                server,
		Sites:                 prepared.sites,
		Dashboard:             prepared.dashboard,
		MaxBodyBytes:          req.MaxBodyBytes,
		TLSDir:                m.tlsDir(),
		HTTPListenPort:        m.HTTPListenPort,
		HTTPSListenPort:       m.HTTPSListenPort,
		SuppressDefaultServer: defaultConflict,
	})
	if err != nil {
		return helperproto.VhostStatusResponse{}, fmt.Errorf("%w: render vhosts: %v", helperproto.ErrInvalidRequest, err)
	}

	previousState, stateErr := m.readState()
	if stateErr != nil {
		previousState = builtinState()
	}
	hadCurrent := m.currentExists(mode)

	writtenTLS, err := m.writeTLSFiles(prepared.dashboard, prepared.tlsSites)
	if err != nil {
		return helperproto.VhostStatusResponse{}, err
	}
	previousOwners := make(map[string]struct{}, len(previousState.TLSOwners))
	for _, owner := range previousState.TLSOwners {
		previousOwners[owner] = struct{}{}
	}
	previousExternal := previousState.Mode == vhostModeNginx || previousState.Mode == vhostModeApache
	cleanupTLS := func() {
		// When the previous mode was external, shared site/dashboard certs are
		// still referenced by the restored release. Remove only owners that
		// did not exist in the previous state; a legacy external state without
		// an owner list keeps every file rather than risking a broken rollback.
		if previousExternal && len(previousOwners) == 0 {
			return
		}
		for _, path := range writtenTLS {
			owner := strings.TrimSuffix(filepath.Base(path), filepath.Ext(path))
			if _, ok := previousOwners[owner]; ok {
				continue
			}
			_ = os.Remove(path)
		}
	}
	cleanupFirstSync := func() {
		cleanupTLS()
	}

	releasePath, releaseName, err := m.writeRelease(mode, files)
	if err != nil {
		cleanupFirstSync()
		return helperproto.VhostStatusResponse{}, err
	}
	cleanupRelease := func() {
		_ = os.RemoveAll(releasePath)
	}

	bridgeCreated := false
	if _, statErr := os.Stat(bridgePath); errors.Is(statErr, fs.ErrNotExist) {
		bridgeCreated = true
	}
	if err := m.ensureBridge(server, bridgePath, previousState.BridgePath, previousState.BridgeHash); err != nil {
		cleanupRelease()
		cleanupFirstSync()
		return helperproto.VhostStatusResponse{}, err
	}
	cleanupFirstSync = func() {
		cleanupTLS()
		if !hadCurrent && bridgeCreated {
			if expected, err := m.bridgeContent(server); err == nil {
				_ = m.removeBridgeFile(bridgePath, expected)
			}
		}
	}

	previousLink, err := m.swapCurrent(mode, releaseName)
	if err != nil {
		cleanupRelease()
		cleanupFirstSync()
		return helperproto.VhostStatusResponse{}, err
	}

	if output, testErr := m.runConfigTest(ctx, mode); testErr != nil {
		restoreErr := m.restoreCurrent(mode, previousLink)
		revertOutput, revertErr := m.runConfigTest(ctx, mode)
		if restoreErr == nil {
			cleanupRelease()
			cleanupFirstSync()
		}
		errs := []error{fmt.Errorf("%w: %s config test failed: %s", helperproto.ErrVhostConfigInvalid, mode, scrubVhostOutput(output))}
		if restoreErr != nil {
			errs = append(errs, fmt.Errorf("restore previous release: %w", restoreErr))
		}
		if revertErr != nil {
			errs = append(errs, fmt.Errorf("config test after rollback failed: %s", scrubVhostOutput(revertOutput)))
		}
		m.persistFailure(previousState, errors.Join(errs...), restoreErr == nil && revertErr == nil)
		return helperproto.VhostStatusResponse{}, errors.Join(errs...)
	}

	if output, reloadErr := m.reloadServerOutput(ctx, mode, runtime.reloadService); reloadErr != nil {
		restoreErr := m.restoreCurrent(mode, previousLink)
		revertOutput, revertErr := m.reloadServerOutput(ctx, mode, runtime.reloadService)
		if restoreErr == nil {
			cleanupRelease()
			cleanupFirstSync()
		}
		errs := []error{fmt.Errorf("%w: reload %s: %s", helperproto.ErrServerReloadFailed, runtime.reloadService, scrubVhostOutput(output))}
		if restoreErr != nil {
			errs = append(errs, fmt.Errorf("restore previous release: %w", restoreErr))
		}
		if revertErr != nil {
			errs = append(errs, fmt.Errorf("reload after rollback failed: %s", scrubVhostOutput(revertOutput)))
		}
		m.persistFailure(previousState, errors.Join(errs...), restoreErr == nil)
		return helperproto.VhostStatusResponse{}, errors.Join(errs...)
	}

	m.pruneReleases(mode, releaseName)
	m.cleanupStaleTLS(previousState.TLSOwners, prepared.owners)

	bridgeHash, err := m.bridgeHash(server)
	if err != nil {
		return helperproto.VhostStatusResponse{}, err
	}
	state := vhostState{
		Mode:                  mode,
		Server:                mode,
		ServerVersion:         runtime.version,
		BridgePath:            bridgePath,
		BridgeHash:            bridgeHash,
		CurrentRelease:        filepath.Join(m.serverTree(mode), "releases", releaseName),
		ReloadService:         runtime.reloadService,
		ConfigOK:              true,
		LastSync:              m.currentTime(),
		DefaultServerConflict: defaultConflict,
		TLSOwners:             append([]string(nil), prepared.owners...),
	}
	if err := m.writeState(state); err != nil {
		return helperproto.VhostStatusResponse{}, fmt.Errorf("%w: %v", helperproto.ErrVhostSyncFailed, err)
	}
	return m.statusFromState(state), nil
}

type preparedVhosts struct {
	sites     []vhost.SiteSpec
	dashboard vhost.DashboardSpec
	tlsSites  []tlsSiteMaterial
	owners    []string
}

type tlsSiteMaterial struct {
	owner   string
	certPEM []byte
	keyPEM  []byte
}

func (m *VhostManager) validateSyncRequest(req helperproto.VHostSyncRequest) (preparedVhosts, error) {
	if req.MaxBodyBytes < 0 {
		return preparedVhosts{}, fmt.Errorf("%w: max_body_bytes must not be negative", helperproto.ErrInvalidRequest)
	}
	if req.Dashboard.BackendPort != dashboardPort {
		return preparedVhosts{}, fmt.Errorf("%w: dashboard backend port must be %d, got %d", helperproto.ErrInvalidRequest, dashboardPort, req.Dashboard.BackendPort)
	}
	dashboardDomains := []string{dashboardDomain}
	dashboardCert, dashboardKey := req.Dashboard.CertPEM, req.Dashboard.KeyPEM
	if len(dashboardCert) == 0 || len(dashboardKey) == 0 {
		return preparedVhosts{}, fmt.Errorf("%w: dashboard certificate and key are required", helperproto.ErrInvalidRequest)
	}
	if err := m.verifyLeaf(dashboardCert, dashboardKey, dashboardDomains, "dashboard"); err != nil {
		return preparedVhosts{}, err
	}
	prepared := preparedVhosts{
		dashboard: vhost.DashboardSpec{
			Domain:  req.Dashboard.Domain,
			UIPort:  req.Dashboard.BackendPort,
			CertPEM: dashboardCert,
			KeyPEM:  dashboardKey,
		},
		owners: []string{dashboardOwner},
		tlsSites: []tlsSiteMaterial{{
			owner: dashboardOwner, certPEM: dashboardCert, keyPEM: dashboardKey,
		}},
	}

	ids := make(map[string]string, len(req.Sites))
	hosts := make(map[string]string, len(req.Sites)*2)
	hosts[dashboardDomain] = "dashboard"
	for _, site := range req.Sites {
		spec, err := m.validateSite(site, ids, hosts)
		if err != nil {
			return preparedVhosts{}, err
		}
		prepared.sites = append(prepared.sites, spec)
		if site.TLS {
			prepared.tlsSites = append(prepared.tlsSites, tlsSiteMaterial{
				owner: site.ID, certPEM: site.CertPEM, keyPEM: site.KeyPEM,
			})
			prepared.owners = append(prepared.owners, site.ID)
		}
	}
	return prepared, nil
}

func (m *VhostManager) validateSite(site helperproto.VHostSite, ids, hosts map[string]string) (vhost.SiteSpec, error) {
	if _, ok := ids[site.ID]; ok {
		return vhost.SiteSpec{}, fmt.Errorf("%w: duplicate site ID %q", helperproto.ErrInvalidRequest, site.ID)
	}
	ids[site.ID] = site.Name

	kind := model.SiteKind(site.Kind)
	spec := vhost.SiteSpec{
		ID:              site.ID,
		Name:            site.Name,
		Domain:          site.Domain,
		WWW:             site.WWW,
		Kind:            kind,
		DocumentRoot:    site.DocumentRoot,
		BackendPort:     site.BackendPort,
		TLS:             site.TLS,
		ForceHTTPS:      site.ForceHTTPS,
		SPAFallback:     site.SPAFallback,
		FrontController: site.FrontController,
		DesiredState:    model.DesiredState(site.DesiredState),
		CertPEM:         site.CertPEM,
		KeyPEM:          site.KeyPEM,
	}
	if err := vhost.ValidateSiteSpec(spec); err != nil {
		return vhost.SiteSpec{}, fmt.Errorf("%w: %v", helperproto.ErrInvalidRequest, err)
	}

	resolvedBackend := ""
	stoppedStatic := kind == model.SiteStatic && model.DesiredState(site.DesiredState) == model.DesiredStopped
	if !stoppedStatic {
		switch {
		case site.BackendPath != "":
			var err error
			resolvedBackend, err = validateBackendPath(site.BackendPath)
			if err != nil {
				return vhost.SiteSpec{}, fmt.Errorf("%w: site %q: %v", helperproto.ErrInvalidRequest, site.ID, err)
			}
		case kind == model.SiteStatic || site.DocumentRoot != "":
			return vhost.SiteSpec{}, fmt.Errorf("%w: site %q: a backend path is required", helperproto.ErrInvalidRequest, site.ID)
		}
		if site.DocumentRoot != "" {
			resolvedRoot, err := validateContainedDocumentRoot(site.DocumentRoot, resolvedBackend)
			if err != nil {
				return vhost.SiteSpec{}, fmt.Errorf("%w: site %q: %v", helperproto.ErrInvalidRequest, site.ID, err)
			}
			spec.DocumentRoot = resolvedRoot
			if kind == model.SiteStatic && model.DesiredState(site.DesiredState) == model.DesiredRunning && os.Geteuid() == 0 {
				if err := staticRootWorkerError(resolvedRoot); err != nil {
					return vhost.SiteSpec{}, fmt.Errorf("%w: site %q: %v", helperproto.ErrInvalidRequest, site.ID, err)
				}
			}
		} else if kind == model.SiteStatic {
			return vhost.SiteSpec{}, fmt.Errorf("%w: site %q: static sites require a document root", helperproto.ErrInvalidRequest, site.ID)
		}
	}

	names := []string{site.Domain}
	if site.WWW {
		names = append(names, "www."+site.Domain)
	}
	for _, name := range names {
		if owner, ok := hosts[name]; ok {
			return vhost.SiteSpec{}, fmt.Errorf("%w: domain %q is already used by %s", helperproto.ErrInvalidRequest, name, owner)
		}
	}
	for _, name := range names {
		hosts[name] = "site " + site.ID
	}

	if site.TLS {
		if err := m.verifyLeaf(site.CertPEM, site.KeyPEM, names, "site "+site.ID); err != nil {
			return vhost.SiteSpec{}, err
		}
	}
	return spec, nil
}

func (m *VhostManager) verifyLeaf(certPEM, keyPEM []byte, domains []string, owner string) error {
	if m.authority == nil {
		return fmt.Errorf("%w: certificate authority is not configured", helperproto.ErrInternal)
	}
	if err := m.authority.VerifyLeaf(certPEM, keyPEM, domains); err != nil {
		return fmt.Errorf("%w: %s certificate: %v", helperproto.ErrInvalidRequest, owner, err)
	}
	return nil
}

func validateBackendPath(raw string) (string, error) {
	if err := validateAbsolutePath("backend path", raw); err != nil {
		return "", err
	}
	resolved, err := filepath.EvalSymlinks(raw)
	if err != nil {
		return "", fmt.Errorf("resolve backend path %q: %w", raw, err)
	}
	info, err := os.Stat(resolved)
	if err != nil {
		return "", fmt.Errorf("stat backend path %q: %w", raw, err)
	}
	if !info.IsDir() {
		return "", fmt.Errorf("backend path %q is not a directory", raw)
	}
	return resolved, nil
}

func validateContainedDocumentRoot(raw, resolvedBackend string) (string, error) {
	if err := validateAbsolutePath("document root", raw); err != nil {
		return "", err
	}
	resolved, err := filepath.EvalSymlinks(raw)
	if err != nil {
		return "", fmt.Errorf("resolve document root %q: %w", raw, err)
	}
	info, err := os.Stat(resolved)
	if err != nil {
		return "", fmt.Errorf("stat document root %q: %w", raw, err)
	}
	if !info.IsDir() {
		return "", fmt.Errorf("document root %q is not a directory", raw)
	}
	if !pathInside(resolved, resolvedBackend) {
		return "", fmt.Errorf("document root %q resolves outside backend path %q", raw, resolvedBackend)
	}
	return resolved, nil
}

func validateAbsolutePath(kind, value string) error {
	if strings.ContainsRune(value, 0) {
		return fmt.Errorf("%s contains NUL", kind)
	}
	if strings.ContainsAny(value, "\n\r") {
		return fmt.Errorf("%s contains a newline", kind)
	}
	if !filepath.IsAbs(value) {
		return fmt.Errorf("%s %q must be absolute", kind, value)
	}
	if filepath.Clean(value) != value {
		return fmt.Errorf("%s %q must be a clean path", kind, value)
	}
	for _, element := range strings.Split(value, "/") {
		if element == ".." {
			return fmt.Errorf("%s %q must not contain ..", kind, value)
		}
	}
	return nil
}

func pathInside(path, parent string) bool {
	rel, err := filepath.Rel(parent, path)
	if err != nil {
		return false
	}
	if rel == "." {
		return true
	}
	return rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))
}

func (m *VhostManager) bridgeContent(server vhost.Server) ([]byte, error) {
	switch server {
	case vhost.ServerNginx:
		return []byte(fmt.Sprintf("%s\n\ninclude %s/*.conf;\n", vhostGeneratedHeader, filepath.Join(m.serverTree(string(server)), "current"))), nil
	case vhost.ServerApache:
		return []byte(fmt.Sprintf("%s\n\nIncludeOptional %s/*.conf\n", vhostGeneratedHeader, filepath.Join(m.serverTree(string(server)), "current"))), nil
	default:
		return nil, fmt.Errorf("%w: unsupported server %q", helperproto.ErrVhostSyncFailed, server)
	}
}

func (m *VhostManager) bridgeHash(server vhost.Server) (string, error) {
	content, err := m.bridgeContent(server)
	if err != nil {
		return "", err
	}
	sum := sha256.Sum256(content)
	return hex.EncodeToString(sum[:]), nil
}

func bridgeDataHash(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

// ensureBridge installs the single managed include file. bridgeHash is the
// content hash recorded in state; when it is present the existing file must
// still match it, so a user edit that keeps the generated header is refused.
// With no recorded hash (a legacy or missing state file), a header-bearing
// bridge is adopted only when it already has exactly the content we generate.
func (m *VhostManager) ensureBridge(server vhost.Server, bridgePath, previousBridgePath, previousHash string) error {
	if err := os.MkdirAll(filepath.Dir(bridgePath), 0o755); err != nil {
		return fmt.Errorf("%w: create include directory %s: %v", helperproto.ErrVhostIncludeMissing, filepath.Dir(bridgePath), err)
	}
	content, err := m.bridgeContent(server)
	if err != nil {
		return err
	}
	existing, err := os.ReadFile(bridgePath)
	switch {
	case err == nil:
		if !hasGeneratedHeader(existing) {
			return fmt.Errorf(
				"%w: refusing to overwrite %s because it was not generated by devstack; remove it, or restore the devstack bridge, and retry",
				helperproto.ErrVhostIncludeMissing, bridgePath)
		}
		if previousBridgePath == bridgePath && previousHash != "" {
			if bridgeDataHash(existing) != previousHash {
				return fmt.Errorf(
					"%w: refusing to overwrite %s because it changed after devstack wrote it; restore the bridge (or delete it and run sync again)",
					helperproto.ErrVhostIncludeMissing, bridgePath)
			}
		} else if !bytes.Equal(existing, content) {
			return fmt.Errorf(
				"%w: refusing to overwrite %s because its content differs and devstack has no ownership record for it; remove it and retry",
				helperproto.ErrVhostIncludeMissing, bridgePath)
		}
		if bytes.Equal(existing, content) {
			return nil
		}
		if err := writeAtomicFile(bridgePath, content, 0o644); err != nil {
			return fmt.Errorf("%w: write bridge %s: %v", helperproto.ErrVhostSyncFailed, bridgePath, err)
		}
		return nil
	case errors.Is(err, fs.ErrNotExist):
		if err := writeAtomicFile(bridgePath, content, 0o644); err != nil {
			return fmt.Errorf("%w: write bridge %s: %v", helperproto.ErrVhostIncludeMissing, bridgePath, err)
		}
		return nil
	default:
		return fmt.Errorf("%w: read bridge %s: %v", helperproto.ErrVhostSyncFailed, bridgePath, err)
	}
}

// verifyBridgeOwnership applies the bridge ownership rule to every removal
// path. A recorded hash must match; without one (legacy state), the content
// must exactly equal the bridge currently generated for this manager and
// server. A header-bearing user edit is therefore never removed or overwritten.
func (m *VhostManager) verifyBridgeOwnership(state vhostState, server string, data []byte) error {
	if !hasGeneratedHeader(data) {
		return fmt.Errorf(
			"%w: refusing to remove %s because it was not generated by devstack; remove it manually or restore the bridge",
			helperproto.ErrVhostIncludeMissing, state.BridgePath)
	}
	if state.BridgeHash != "" {
		if bridgeDataHash(data) != state.BridgeHash {
			return fmt.Errorf(
				"%w: refusing to remove %s because it changed after devstack wrote it; restore the bridge and retry",
				helperproto.ErrVhostIncludeMissing, state.BridgePath)
		}
		return nil
	}
	var servers []vhost.Server
	switch vhost.Server(server) {
	case vhost.ServerNginx, vhost.ServerApache:
		servers = []vhost.Server{vhost.Server(server)}
	default:
		servers = []vhost.Server{vhost.ServerNginx, vhost.ServerApache}
	}
	for _, candidate := range servers {
		expected, err := m.bridgeContent(candidate)
		if err == nil && bytes.Equal(data, expected) {
			return nil
		}
	}
	return fmt.Errorf(
		"%w: refusing to remove %s because devstack has no ownership record and its content does not match the generated bridge; remove it manually",
		helperproto.ErrVhostIncludeMissing, state.BridgePath)
}

// removeBridgeFile removes a bridge this sync created. It refuses if the file
// no longer exactly matches the content that was just generated.
func (m *VhostManager) removeBridgeFile(path string, expected []byte) error {
	data, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	if !bytes.Equal(data, expected) {
		return fmt.Errorf("%w: refusing to remove %s because it changed after devstack wrote it", helperproto.ErrVhostIncludeMissing, path)
	}
	return os.Remove(path)
}

func (m *VhostManager) removeBridge(state vhostState) error {
	if state.BridgePath == "" {
		return nil
	}
	data, err := os.ReadFile(state.BridgePath)
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	server := state.Server
	if server == "" {
		server = state.Mode
	}
	if err := m.verifyBridgeOwnership(state, server, data); err != nil {
		return err
	}
	return os.Remove(state.BridgePath)
}

func (m *VhostManager) restoreBridge(path string, data []byte) error {
	if path == "" || len(data) == 0 {
		return nil
	}
	return writeAtomicFile(path, data, 0o644)
}

func hasGeneratedHeader(data []byte) bool {
	return bytes.HasPrefix(data, []byte(vhostGeneratedHeader+"\n"))
}

func (m *VhostManager) writeTLSFiles(dashboard vhost.DashboardSpec, sites []tlsSiteMaterial) ([]string, error) {
	dir := m.tlsDir()
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return nil, fmt.Errorf("%w: create TLS directory %s: %v", helperproto.ErrVhostSyncFailed, dir, err)
	}
	_ = os.Chmod(dir, 0o700)
	var written []string
	writeOne := func(owner string, certPEM, keyPEM []byte) error {
		certPath := filepath.Join(dir, owner+".crt")
		keyPath := filepath.Join(dir, owner+".key")
		if err := writeTLSFilePair(certPath, keyPath, certPEM, keyPEM); err != nil {
			return err
		}
		written = append(written, certPath, keyPath)
		return nil
	}
	if err := writeOne(dashboardOwner, dashboard.CertPEM, dashboard.KeyPEM); err != nil {
		return written, err
	}
	for _, site := range sites {
		if err := writeOne(site.owner, site.certPEM, site.keyPEM); err != nil {
			return written, err
		}
	}
	return written, nil
}

func writeTLSFilePair(certPath, keyPath string, certPEM, keyPEM []byte) error {
	if err := writeAtomicFile(keyPath, keyPEM, 0o600); err != nil {
		return fmt.Errorf("%w: write key %s: %v", helperproto.ErrVhostSyncFailed, keyPath, err)
	}
	if err := writeAtomicFile(certPath, certPEM, 0o644); err != nil {
		return fmt.Errorf("%w: write certificate %s: %v", helperproto.ErrVhostSyncFailed, certPath, err)
	}
	return nil
}

func (m *VhostManager) removeTLSFiles(owners []string) error {
	var errs []error
	for _, owner := range owners {
		if !safeOwner(owner) {
			continue
		}
		for _, ext := range []string{".crt", ".key"} {
			path := filepath.Join(m.tlsDir(), owner+ext)
			if err := os.Remove(path); err != nil && !errors.Is(err, fs.ErrNotExist) {
				errs = append(errs, fmt.Errorf("remove %s: %w", path, err))
			}
		}
	}
	return errors.Join(errs...)
}

func (m *VhostManager) cleanupStaleTLS(previous, current []string) {
	keep := make(map[string]struct{}, len(current))
	for _, owner := range current {
		keep[owner] = struct{}{}
	}
	var stale []string
	for _, owner := range previous {
		if _, ok := keep[owner]; !ok {
			stale = append(stale, owner)
		}
	}
	if len(stale) > 0 {
		_ = m.removeTLSFiles(stale)
	}
}

func safeOwner(owner string) bool {
	if owner == dashboardOwner {
		return true
	}
	if owner == "" || len(owner) > 63 {
		return false
	}
	for i := 0; i < len(owner); i++ {
		c := owner[i]
		switch {
		case c >= 'a' && c <= 'z', c >= '0' && c <= '9', c == '-':
		default:
			return false
		}
	}
	return owner[0] != '-' && owner[len(owner)-1] != '-'
}

func (m *VhostManager) writeRelease(mode string, files map[string][]byte) (string, string, error) {
	serverDir := m.serverTree(mode)
	releasesDir := filepath.Join(serverDir, "releases")
	if err := os.MkdirAll(releasesDir, 0o755); err != nil {
		return "", "", fmt.Errorf("%w: create releases directory %s: %v", helperproto.ErrVhostSyncFailed, releasesDir, err)
	}
	stamp := m.currentTime().Format("20060102T150405Z")
	name := stamp
	for suffix := 2; ; suffix++ {
		_, err := os.Lstat(filepath.Join(releasesDir, name))
		if errors.Is(err, fs.ErrNotExist) {
			break
		}
		if err != nil {
			return "", "", fmt.Errorf("%w: inspect releases: %v", helperproto.ErrVhostSyncFailed, err)
		}
		name = fmt.Sprintf("%s-%d", stamp, suffix)
	}
	releasePath := filepath.Join(releasesDir, name)
	if err := os.Mkdir(releasePath, 0o755); err != nil {
		return "", "", fmt.Errorf("%w: create release %s: %v", helperproto.ErrVhostSyncFailed, releasePath, err)
	}
	_ = os.Chmod(releasePath, 0o755)
	names := make([]string, 0, len(files))
	for file := range files {
		names = append(names, file)
	}
	sort.Strings(names)
	for _, file := range names {
		if filepath.Base(file) != file {
			_ = os.RemoveAll(releasePath)
			return "", "", fmt.Errorf("%w: rendered filename %q is not a base name", helperproto.ErrVhostSyncFailed, file)
		}
		if err := writeAtomicFile(filepath.Join(releasePath, file), files[file], 0o644); err != nil {
			_ = os.RemoveAll(releasePath)
			return "", "", fmt.Errorf("%w: write release file %s: %v", helperproto.ErrVhostSyncFailed, file, err)
		}
	}
	syncDir(releasePath)
	syncDir(releasesDir)
	return releasePath, name, nil
}

func (m *VhostManager) currentExists(mode string) bool {
	_, err := os.Lstat(filepath.Join(m.serverTree(mode), "current"))
	return err == nil
}

func (m *VhostManager) swapCurrent(mode, releaseName string) (string, error) {
	serverDir := m.serverTree(mode)
	currentPath := filepath.Join(serverDir, "current")
	previous := ""
	if target, err := os.Readlink(currentPath); err == nil {
		previous = target
	} else if !errors.Is(err, fs.ErrNotExist) {
		return "", fmt.Errorf("%w: read current link %s: %v", helperproto.ErrVhostSyncFailed, currentPath, err)
	}
	tmp := filepath.Join(serverDir, fmt.Sprintf(".current-%d", time.Now().UnixNano()))
	if err := os.Symlink(filepath.Join("releases", releaseName), tmp); err != nil {
		return "", fmt.Errorf("%w: stage current link: %v", helperproto.ErrVhostSyncFailed, err)
	}
	if err := os.Rename(tmp, currentPath); err != nil {
		_ = os.Remove(tmp)
		return "", fmt.Errorf("%w: swap current link: %v", helperproto.ErrVhostSyncFailed, err)
	}
	syncDir(serverDir)
	return previous, nil
}

func (m *VhostManager) restoreCurrent(mode, previous string) error {
	serverDir := m.serverTree(mode)
	currentPath := filepath.Join(serverDir, "current")
	if previous == "" {
		if err := os.Remove(currentPath); err != nil && !errors.Is(err, fs.ErrNotExist) {
			return err
		}
		syncDir(serverDir)
		return nil
	}
	tmp := filepath.Join(serverDir, fmt.Sprintf(".current-%d", time.Now().UnixNano()))
	if err := os.Symlink(previous, tmp); err != nil {
		return err
	}
	if err := os.Rename(tmp, currentPath); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	syncDir(serverDir)
	return nil
}

func (m *VhostManager) pruneReleases(mode, currentName string) {
	dir := filepath.Join(m.serverTree(mode), "releases")
	entries, err := os.ReadDir(dir)
	if err != nil {
		return
	}
	var ours []string
	for _, entry := range entries {
		if !entry.IsDir() {
			continue
		}
		if releaseNamePattern.MatchString(entry.Name()) {
			ours = append(ours, entry.Name())
		}
	}
	sort.Strings(ours)
	keep := map[string]struct{}{currentName: {}}
	for i := len(ours) - 1; i >= 0 && len(keep) < 2; i-- {
		keep[ours[i]] = struct{}{}
	}
	for _, name := range ours {
		if _, ok := keep[name]; ok {
			continue
		}
		_ = os.RemoveAll(filepath.Join(dir, name))
	}
}

func (m *VhostManager) removeEmptyServerDirs() {
	for _, server := range []string{vhostModeNginx, vhostModeApache} {
		serverDir := m.serverTree(server)
		releasesDir := filepath.Join(serverDir, "releases")
		if entries, err := os.ReadDir(releasesDir); err == nil && len(entries) == 0 {
			_ = os.Remove(releasesDir)
		}
		if entries, err := os.ReadDir(serverDir); err == nil && len(entries) == 0 {
			_ = os.Remove(serverDir)
		}
	}
}

func (m *VhostManager) removeAllManagedServerFiles() error {
	return errors.Join(
		m.removeManagedServerFiles(vhostModeNginx),
		m.removeManagedServerFiles(vhostModeApache),
	)
}

func (m *VhostManager) removeManagedServerFiles(mode string) error {
	serverDir := m.serverTree(mode)
	currentPath := filepath.Join(serverDir, "current")
	if info, err := os.Lstat(currentPath); err == nil {
		if info.Mode()&os.ModeSymlink == 0 {
			return fmt.Errorf("%w: refusing to remove non-symlink %s", helperproto.ErrVhostSyncFailed, currentPath)
		}
		if err := os.Remove(currentPath); err != nil && !errors.Is(err, fs.ErrNotExist) {
			return fmt.Errorf("%w: remove current link: %v", helperproto.ErrVhostSyncFailed, err)
		}
	} else if !errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("%w: inspect current link: %v", helperproto.ErrVhostSyncFailed, err)
	}
	releasesDir := filepath.Join(serverDir, "releases")
	entries, err := os.ReadDir(releasesDir)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("%w: read releases: %v", helperproto.ErrVhostSyncFailed, err)
	}
	for _, entry := range entries {
		if !entry.IsDir() || !releaseNamePattern.MatchString(entry.Name()) {
			continue
		}
		if err := os.RemoveAll(filepath.Join(releasesDir, entry.Name())); err != nil {
			return fmt.Errorf("%w: remove release %s: %v", helperproto.ErrVhostSyncFailed, entry.Name(), err)
		}
	}
	if entries, err := os.ReadDir(releasesDir); err == nil && len(entries) == 0 {
		_ = os.Remove(releasesDir)
	}
	if entries, err := os.ReadDir(serverDir); err == nil && len(entries) == 0 {
		_ = os.Remove(serverDir)
	}
	return nil
}

func (m *VhostManager) persistFailure(previous vhostState, cause error, configOK bool) {
	if err := m.writeState(m.failureState(previous, cause, configOK)); err != nil {
		m.logger.Warn("helper: persist vhost failure state", "error", err)
	}
}

var (
	pemBlockPattern   = regexp.MustCompile(`(?s)-----BEGIN [^-]+-----.*?-----END [^-]+-----`)
	secretLinePattern = regexp.MustCompile(`(?im)^.*(private key|ssl_certificate_key|sslcertificatekeyfile|passphrase|password|secret|token).*$`)
)

// scrubVhostOutput removes PEM material and secret-looking lines from server
// output and truncates long messages before they reach a client or the state.
func scrubVhostOutput(data []byte) string {
	text := string(data)
	text = pemBlockPattern.ReplaceAllString(text, "[redacted PEM]")
	text = secretLinePattern.ReplaceAllString(text, "[redacted secret line]")
	text = strings.TrimSpace(text)
	if len(text) > outputLimit {
		text = text[:outputLimit] + "...(truncated)"
	}
	return text
}
