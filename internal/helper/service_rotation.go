// InputCommandRunner is an optional CommandRunner extension for fixed helper
// commands that must receive secret input on stdin instead of argv.
type InputCommandRunner interface {
	RunInput(ctx context.Context, input []byte, name string, args ...string) ([]byte, error)
}

// ServiceSecretStore is the host-secret surface used by credential rotation.
type ServiceSecretStore interface {
	Read(engine, name string) (string, error)
	Replace(engine, name, value string) error
}

// Secret rotation accepts only the 32-byte hex values generated by
// credentials.NewSecret. This keeps the password safe to embed in SQL passed on
// stdin and rejects accidental shell metacharacters.
var rotationSecretPattern = regexp.MustCompile(`^[0-9a-f]{64}$`)

// RotateCredentials updates the live devstack database account and then commits
// the new value to the host secret file. The previous value stays in place
// until the database update succeeds. Passwords are never passed in argv.
func (c *DockerServiceController) RotateCredentials(ctx context.Context, id services.ID) error {
	if _, err := c.service(id); err != nil {
		return err
	}
	if !rotatableDatabase(id) {
		return fmt.Errorf("%w: service %q does not support credential rotation", helperproto.ErrInvalidRequest, id)
	}

	c.opMu.Lock()
	defer c.opMu.Unlock()

	if err := c.ensureComposeFile(); err != nil {
		return err
	}
	containers, err := c.containers(ctx)
	if err != nil {
		return err
	}
	cont, ok := containers[string(id)]
	if !ok || !strings.EqualFold(cont.State, "running") {
		return fmt.Errorf("%w: service %q must be active to rotate credentials", helperproto.ErrServiceConflict, id)
	}

	secrets := c.secretStore()
	oldPassword, err := secrets.Read(string(id), "devstack_password")
	if err != nil {
		return fmt.Errorf("read %s credentials: %w", id, err)
	}
	if !rotationSecretPattern.MatchString(oldPassword) {
		// Refuse to change the account when the host secret cannot be used for
		// an automatic rollback. The operator can reset it explicitly.
		return fmt.Errorf("%w: service %q has a non-managed devstack credential; reset it before rotating", helperproto.ErrInvalidRequest, id)
	}
	newPassword, err := credentials.NewSecret()
	if err != nil {
		return err
	}
	newSQL, err := rotationSQL(id, newPassword)
	if err != nil {
		return err
	}
	args, err := rotationCommand(id)
	if err != nil {
		return err
	}

	if _, err := c.runComposeInput(ctx, []byte(newSQL), args...); err != nil {
		return rotationFailure(id, "update database account", err, oldPassword, newPassword)
	}
	if err := secrets.Replace(string(id), "devstack_password", newPassword); err != nil {
		oldSQL, buildErr := rotationSQL(id, oldPassword)
		if buildErr != nil {
			return fmt.Errorf("rotate %s credentials: store new secret: %v", id, err)
		}
		if _, rollbackErr := c.runComposeInput(ctx, []byte(oldSQL), args...); rollbackErr != nil {
			return rotationFailure(id,
				"store new secret and restore the previous database password", errors.Join(err, rollbackErr),
				oldPassword, newPassword)
		}
		return fmt.Errorf("rotate %s credentials: store new secret: %v; the database account was restored", id, err)
	}
	return nil
}

func rotatableDatabase(id services.ID) bool {
	switch id {
	case services.IDMySQL, services.IDMariaDB, services.IDPostgreSQL:
		return true
	default:
		return false
	}
}

func rotationSQL(id services.ID, password string) (string, error) {
	if !rotationSecretPattern.MatchString(password) {
		return "", fmt.Errorf("%w: invalid generated password", helperproto.ErrInternal)
	}
	switch id {
	case services.IDMySQL, services.IDMariaDB:
		return fmt.Sprintf("ALTER USER 'devstack'@'%%' IDENTIFIED BY '%s';\nFLUSH PRIVILEGES;\n", password), nil
	case services.IDPostgreSQL:
		return fmt.Sprintf("ALTER ROLE devstack WITH PASSWORD '%s';\n", password), nil
	default:
		return "", fmt.Errorf("%w: service %q does not support credential rotation", helperproto.ErrInvalidRequest, id)
	}
}

// rotationCommand returns the fixed Compose exec arguments. MySQL and MariaDB
// read the mounted root secret inside the container; PostgreSQL uses the
// local-socket trust rule generated in pg_hba.conf. The new password travels
// only on stdin.
func rotationCommand(id services.ID) ([]string, error) {
	switch id {
	case services.IDMySQL:
		return []string{
			"exec", "-T", string(id), "sh", "-c",
			`set -eu; MYSQL_PWD="$(cat /run/secrets/mysql_root_password)"; export MYSQL_PWD; exec mysql --user=root --batch --skip-column-names`,
		}, nil
	case services.IDMariaDB:
		return []string{
			"exec", "-T", string(id), "sh", "-c",
			`set -eu; MYSQL_PWD="$(cat /run/secrets/mariadb_root_password)"; export MYSQL_PWD; exec mariadb --user=root --batch --skip-column-names`,
		}, nil
	case services.IDPostgreSQL:
		return []string{
			"exec", "-T", string(id), "psql", "--no-psqlrc", "--set=ON_ERROR_STOP=1",
			"--username=postgres", "--dbname=postgres",
		}, nil
	default:
		return nil, fmt.Errorf("%w: service %q does not support credential rotation", helperproto.ErrInvalidRequest, id)
	}
}

func (c *DockerServiceController) runComposeInput(ctx context.Context, input []byte, args ...string) ([]byte, error) {
	runner, ok := c.runner.(InputCommandRunner)
	if !ok {
		return nil, fmt.Errorf("%w: command runner does not support stdin", helperproto.ErrInternal)
	}
	base := []string{"compose", "-p", c.projectName, "-f", c.composePath}
	return runner.RunInput(ctx, input, "docker", append(base, args...)...)
}

func (c *DockerServiceController) secretStore() ServiceSecretStore {
	if c.Secrets != nil {
		return c.Secrets
	}
	return &credentials.Store{Root: c.root}
}

func rotationFailure(id services.ID, operation string, cause error, secrets ...string) error {
	return fmt.Errorf("%w: rotate %s credentials: %s: %s",
		helperproto.ErrInternal, id, operation, scrubSecretText(cause.Error(), secrets...))
}

func scrubSecretText(text string, secrets ...string) string {
	for _, secret := range secrets {
		if secret != "" {
			text = strings.ReplaceAll(text, secret, "[REDACTED]")
		}
	}
	return text
}
