// Package vhost validates site descriptions and renders native nginx and
// Apache virtual host files for externally served devstack sites. Rendering is
// pure: this package never reads or writes the filesystem, and it never invokes
// the privileged helper.
package vhost

import (
	"errors"
	"fmt"
	"path/filepath"
	"strings"
	"time"

	"github.com/AramZahedi/dev-web-stack/internal/domain"
	"github.com/AramZahedi/dev-web-stack/internal/model"
)

// Server identifies a supported external web server.
type Server string

const (
	ServerNginx  Server = "nginx"
	ServerApache Server = "apache"
)

// Mode is the configured serving mode. Exactly one mode is active.
type Mode string

const (
	ModeBuiltin Mode = "builtin"
	ModeNginx   Mode = "nginx"
	ModeApache  Mode = "apache"
)

// SiteSpec is the validated description of one site vhost. Certificate bytes
// are used only to prove that material was supplied; they are never rendered.
type SiteSpec struct {
	ID              string
	Name            string
	Domain          string
	WWW             bool
	Kind            model.SiteKind
	DocumentRoot    string
	BackendPort     int
	TLS             bool
	ForceHTTPS      bool
	SPAFallback     bool
	FrontController bool
	DesiredState    model.DesiredState
	CertPEM         []byte
	KeyPEM          []byte
	CertNotAfter    time.Time
}

// DashboardSpec describes the dashboard vhost.
type DashboardSpec struct {
	Domain  string
	UIPort  int
	CertPEM []byte
	KeyPEM  []byte
}

// Set is a complete vhost render request.
type Set struct {
	Server       Server
	Sites        []SiteSpec
	Dashboard    DashboardSpec
	MaxBodyBytes int64
	// TLSDir is the directory containing the certificate and key files
	// referenced by the rendered configs. An empty value uses the production
	// default /etc/devstack/tls.
	TLSDir string
	// HTTPListenPort and HTTPSListenPort are the listen ports used in the
	// rendered configs. Zero selects the production defaults, 80 and 443.
	// They exist so tests can run a real server unprivileged on high ports;
	// production always uses 80/443.
	HTTPListenPort  int
	HTTPSListenPort int
}

// listenPorts is the resolved pair of ports used while rendering one set.
type listenPorts struct {
	http  int
	https int
}

// ErrPHPUnsupported reports that a PHP vhost was requested before Plan 2 ships
// the FastCGI templates.
var ErrPHPUnsupported = errors.New("PHP vhosts arrive with Plan 2")

const (
	generatedHeader     = "# Generated by devstack. Do not edit."
	generatedHTMLHeader = "<!-- Generated by devstack. Do not edit. -->"

	defaultTLSDir   = "/etc/devstack/tls"
	dashboardDomain = "devstack.test"

	defaultHTTPListenPort  = 80
	defaultHTTPSListenPort = 443

	defaultMaxBodyBytes int64 = 1024 * 1024 * 1024
	minNodePort               = 41000
	maxNodePort               = 42999
	maxSlugLen                = 63
)

// ValidateListenPorts validates a pair of vhost listen ports. A zero value
// selects the production default for that scheme (80 or 443); everything else
// must be a valid TCP port and the two resolved ports must differ.
func ValidateListenPorts(httpPort, httpsPort int) error {
	_, err := resolveListenPorts(httpPort, httpsPort)
	return err
}

// schemeDefaultPort returns the default port for a redirect target scheme.
func schemeDefaultPort(scheme string) int {
	if scheme == "https" {
		return defaultHTTPSListenPort
	}
	return defaultHTTPListenPort
}

func resolveListenPorts(httpPort, httpsPort int) (listenPorts, error) {
	if httpPort == 0 {
		httpPort = defaultHTTPListenPort
	}
	if httpsPort == 0 {
		httpsPort = defaultHTTPSListenPort
	}
	if httpPort < 1 || httpPort > 65535 {
		return listenPorts{}, fmt.Errorf("vhost: HTTP listen port %d must be between 1 and 65535", httpPort)
	}
	if httpsPort < 1 || httpsPort > 65535 {
		return listenPorts{}, fmt.Errorf("vhost: HTTPS listen port %d must be between 1 and 65535", httpsPort)
	}
	if httpPort == httpsPort {
		return listenPorts{}, fmt.Errorf("vhost: HTTP and HTTPS listen ports must differ, both are %d", httpPort)
	}
	return listenPorts{http: httpPort, https: httpsPort}, nil
}

// ValidateSiteSpec validates one site using syntactic checks only. It never
// stats, resolves symlinks, or otherwise touches the filesystem; existence,
// directory type, symlink resolution, and backend containment are enforced by
// the privileged helper when it installs the rendered files.
func ValidateSiteSpec(s SiteSpec) error {
	if err := validateSlug("site ID", s.ID); err != nil {
		return err
	}
	if err := validateSlug("site name", s.Name); err != nil {
		return err
	}
	if err := domain.ValidateSiteDomain(s.Domain); err != nil {
		return fmt.Errorf("vhost: site %q: %w", s.ID, err)
	}

	if s.FrontController || s.Kind == model.SitePHP {
		return fmt.Errorf("vhost: site %q: %w", s.ID, ErrPHPUnsupported)
	}

	switch s.Kind {
	case model.SiteStatic:
		if s.DesiredState == model.DesiredRunning && s.DocumentRoot == "" {
			return fmt.Errorf("vhost: site %q: static sites require a document root", s.ID)
		}
		if s.BackendPort != 0 {
			return fmt.Errorf("vhost: site %q: static site backend port must be 0, got %d", s.ID, s.BackendPort)
		}
	case model.SiteNode:
		// A stopped Node vhost renders a branded 503 and never dials the
		// backend, so a zero port is acceptable only while stopped.
		if s.BackendPort != 0 || s.DesiredState == model.DesiredRunning {
			if s.BackendPort < minNodePort || s.BackendPort > maxNodePort {
				return fmt.Errorf("vhost: site %q: node backend port %d is outside %d-%d", s.ID, s.BackendPort, minNodePort, maxNodePort)
			}
		}
	default:
		return fmt.Errorf("vhost: site %q: unsupported site kind %q", s.ID, s.Kind)
	}

	if s.DocumentRoot != "" {
		if err := validateDocumentRoot(s.DocumentRoot); err != nil {
			return fmt.Errorf("vhost: site %q: %w", s.ID, err)
		}
	}

	switch s.DesiredState {
	case model.DesiredRunning, model.DesiredStopped:
	default:
		return fmt.Errorf("vhost: site %q: invalid desired state %q", s.ID, s.DesiredState)
	}

	if s.ForceHTTPS && !s.TLS {
		return fmt.Errorf("vhost: site %q: force HTTPS requires TLS", s.ID)
	}
	if s.TLS {
		if len(s.CertPEM) == 0 {
			return fmt.Errorf("vhost: site %q: TLS requires a certificate", s.ID)
		}
		if len(s.KeyPEM) == 0 {
			return fmt.Errorf("vhost: site %q: TLS requires a private key", s.ID)
		}
	}
	return nil
}

// validateSlug enforces the lowercase DNS label shape used for site IDs and
// names. IDs become certificate owners and name/id pairs become filenames, so
// anything outside [a-z0-9-] is rejected rather than normalized.
func validateSlug(kind, value string) error {
	if value == "" {
		return fmt.Errorf("vhost: %s is empty", kind)
	}
	if len(value) > maxSlugLen {
		return fmt.Errorf("vhost: %s %q is longer than %d characters", kind, value, maxSlugLen)
	}
	for i := 0; i < len(value); i++ {
		c := value[i]
		switch {
		case c >= 'a' && c <= 'z', c >= '0' && c <= '9', c == '-':
		default:
			return fmt.Errorf("vhost: %s %q contains invalid character %q", kind, value, string(c))
		}
	}
	if value[0] == '-' || value[len(value)-1] == '-' {
		return fmt.Errorf("vhost: %s %q must not start or end with a hyphen", kind, value)
	}
	return nil
}

// validateDocumentRoot performs syntactic validation only: absolute, clean, no
// traversal element, and no NUL or newline. It deliberately does not consult
// the filesystem. A dollar sign is rejected because nginx cannot represent a
// literal dollar in a directive value; it always starts a variable reference.
func validateDocumentRoot(root string) error {
	if strings.ContainsRune(root, 0) {
		return errors.New("document root contains NUL")
	}
	if strings.ContainsAny(root, "\n\r") {
		return errors.New("document root contains a newline")
	}
	if strings.ContainsRune(root, '$') {
		return errors.New("document root contains '$', which nginx treats as a variable reference")
	}
	if !filepath.IsAbs(root) {
		return fmt.Errorf("document root %q must be absolute", root)
	}
	if filepath.Clean(root) != root {
		return fmt.Errorf("document root %q must be a clean path", root)
	}
	for _, element := range strings.Split(root, "/") {
		if element == ".." {
			return fmt.Errorf("document root %q must not contain ..", root)
		}
	}
	return nil
}

func validateDashboardSpec(d DashboardSpec) error {
	if err := domain.ValidateDomain(d.Domain); err != nil {
		return fmt.Errorf("vhost: dashboard: %w", err)
	}
	if d.Domain != dashboardDomain {
		return fmt.Errorf("vhost: dashboard domain %q must be %q", d.Domain, dashboardDomain)
	}
	if d.UIPort < 1 || d.UIPort > 65535 {
		return fmt.Errorf("vhost: dashboard UI port %d is out of range", d.UIPort)
	}
	if len(d.CertPEM) == 0 {
		return errors.New("vhost: dashboard TLS requires a certificate")
	}
	if len(d.KeyPEM) == 0 {
		return errors.New("vhost: dashboard TLS requires a private key")
	}
	return nil
}

// Render renders the complete file set for a server: every site config, the
// dashboard, the default 404 vhost, and the shared maintenance body.
func Render(set Set) (map[string][]byte, error) {
	if err := validateServer(set.Server); err != nil {
		return nil, err
	}
	if set.MaxBodyBytes < 0 {
		return nil, errors.New("vhost: max body bytes must not be negative")
	}
	maxBody := set.MaxBodyBytes
	if maxBody == 0 {
		maxBody = defaultMaxBodyBytes
	}
	if err := validateDashboardSpec(set.Dashboard); err != nil {
		return nil, err
	}
	tlsDir := set.TLSDir
	if tlsDir == "" {
		tlsDir = defaultTLSDir
	}
	if err := validateTLSDir(tlsDir); err != nil {
		return nil, err
	}
	ports, err := resolveListenPorts(set.HTTPListenPort, set.HTTPSListenPort)
	if err != nil {
		return nil, err
	}

	files := make(map[string][]byte, len(set.Sites)+3)
	owners := make(map[string]string, len(set.Sites))
	for _, site := range set.Sites {
		if err := ValidateSiteSpec(site); err != nil {
			return nil, err
		}
		name := siteFilename(site)
		if previous, ok := owners[name]; ok {
			return nil, fmt.Errorf("vhost: sites %q and %q generate the same filename %q", previous, site.ID, name)
		}
		owners[name] = site.ID

		data, err := renderSite(set.Server, site, maxBody, tlsDir, ports)
		if err != nil {
			return nil, err
		}
		files[name] = data
	}

	dashboard, err := renderDashboard(set.Server, set.Dashboard, maxBody, tlsDir, ports)
	if err != nil {
		return nil, err
	}
	files["_devstack.test.conf"] = dashboard
	files["_default.conf"] = renderDefault(set.Server, tlsDir, ports)
	files["_maintenance.html"] = maintenanceFile()
	return files, nil
}

// RenderSite renders one site config containing both its HTTP and HTTPS server
// blocks. It uses the default request body limit.
func RenderSite(server Server, s SiteSpec) ([]byte, error) {
	if err := validateServer(server); err != nil {
		return nil, err
	}
	if err := ValidateSiteSpec(s); err != nil {
		return nil, err
	}
	return renderSite(server, s, defaultMaxBodyBytes, defaultTLSDir, listenPorts{
		http:  defaultHTTPListenPort,
		https: defaultHTTPSListenPort,
	})
}

func validateServer(server Server) error {
	switch server {
	case ServerNginx, ServerApache:
		return nil
	default:
		return fmt.Errorf("vhost: unsupported server %q", server)
	}
}

func renderSite(server Server, s SiteSpec, maxBody int64, tlsDir string, ports listenPorts) ([]byte, error) {
	switch server {
	case ServerNginx:
		return renderNginxSite(s, maxBody, tlsDir, ports), nil
	case ServerApache:
		return renderApacheSite(s, maxBody, tlsDir, ports), nil
	default:
		return nil, fmt.Errorf("vhost: unsupported server %q", server)
	}
}

func renderDashboard(server Server, d DashboardSpec, maxBody int64, tlsDir string, ports listenPorts) ([]byte, error) {
	switch server {
	case ServerNginx:
		return renderNginxDashboard(d, maxBody, tlsDir, ports), nil
	case ServerApache:
		return renderApacheDashboard(d, maxBody, tlsDir, ports), nil
	default:
		return nil, fmt.Errorf("vhost: unsupported server %q", server)
	}
}

func renderDefault(server Server, tlsDir string, ports listenPorts) []byte {
	switch server {
	case ServerNginx:
		return renderNginxDefault(tlsDir, ports)
	case ServerApache:
		return renderApacheDefault(tlsDir, ports)
	default:
		return nil
	}
}

// siteFilename is stable: the validated name plus the first eight ID
// characters (or the whole ID when shorter).
func siteFilename(s SiteSpec) string {
	id := s.ID
	if len(id) > 8 {
		id = id[:8]
	}
	return s.Name + "-" + id + ".conf"
}

func siteServerNames(s SiteSpec) string {
	if s.WWW {
		return s.Domain + " www." + s.Domain
	}
	return s.Domain
}

func siteCertificatePaths(s SiteSpec, tlsDir string) (certPath, keyPath string) {
	if !s.TLS {
		return dashboardCertificatePaths(tlsDir)
	}
	return tlsDir + "/" + s.ID + ".crt", tlsDir + "/" + s.ID + ".key"
}

func dashboardCertificatePaths(tlsDir string) (certPath, keyPath string) {
	return tlsDir + "/__dashboard__.crt", tlsDir + "/__dashboard__.key"
}

// validateTLSDir performs the syntactic checks applied to the configurable TLS
// directory. It never touches the filesystem.
func validateTLSDir(dir string) error {
	if strings.ContainsRune(dir, 0) {
		return errors.New("vhost: TLS directory contains NUL")
	}
	if strings.ContainsAny(dir, "\n\r") {
		return errors.New("vhost: TLS directory contains a newline")
	}
	if !filepath.IsAbs(dir) {
		return fmt.Errorf("vhost: TLS directory %q must be absolute", dir)
	}
	if filepath.Clean(dir) != dir {
		return fmt.Errorf("vhost: TLS directory %q must be a clean path", dir)
	}
	for _, element := range strings.Split(dir, "/") {
		if element == ".." {
			return fmt.Errorf("vhost: TLS directory %q must not contain ..", dir)
		}
	}
	return nil
}

func maintenanceFile() []byte {
	return []byte(generatedHTMLHeader + "\n" + maintenanceHTML + "\n")
}

