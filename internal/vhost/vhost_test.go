func TestMaxBodyBytes(t *testing.T) {
	tests := []struct {
		server Server
		want   string
	}{
		{ServerNginx, "client_max_body_size 1073741824;"},
		{ServerApache, "LimitRequestBody 1073741824"},
	}
	for _, tc := range tests {
		t.Run(string(tc.server), func(t *testing.T) {
			files, err := Render(testSet(tc.server, 0))
			if err != nil {
				t.Fatalf("Render: %v", err)
			}
			if !bytes.Contains(files["blog-1a2b3c4d.conf"], []byte(tc.want)) {
				t.Fatalf("default body limit %q missing from %s vhost", tc.want, tc.server)
			}

			files, err = Render(testSet(tc.server, 5242880))
			if err != nil {
				t.Fatalf("Render with custom body limit: %v", err)
			}
			want := "client_max_body_size 5242880;"
			if tc.server == ServerApache {
				want = "LimitRequestBody 5242880"
			}
			if !bytes.Contains(files["shop-5e6f7a8b.conf"], []byte(want)) {
				t.Fatalf("custom body limit %q missing from %s node vhost", want, tc.server)
			}

			if _, err := Render(testSet(tc.server, -1)); err == nil {
				t.Fatalf("%s accepted a negative body limit", tc.server)
			}
		})
	}
}

