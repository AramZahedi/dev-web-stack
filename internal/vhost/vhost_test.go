// compareGolden compares rendered bytes against testdata/name. Run the tests
// with UPDATE_GOLDEN=1 to regenerate the files after reviewing the diff.
func compareGolden(t *testing.T, name string, got []byte) {
	t.Helper()
	path := filepath.Join("testdata", filepath.FromSlash(name))
	if os.Getenv("UPDATE_GOLDEN") == "1" {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatalf("create golden directory: %v", err)
		}
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatalf("write golden %s: %v", path, err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read golden %s: %v (run UPDATE_GOLDEN=1 go test ./internal/vhost)", path, err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("%s does not match %s\n--- got ---\n%s\n--- want ---\n%s", name, path, got, want)
	}
}

func TestRenderSet(t *testing.T) {
	wantNames := []string{
		"_default.conf",
		"_devstack.test.conf",
		"_maintenance.html",
		"blog-1a2b3c4d.conf",
		"shop-5e6f7a8b.conf",
	}
	for _, server := range []Server{ServerNginx, ServerApache} {
		t.Run(string(server), func(t *testing.T) {
			files, err := Render(testSet(server, 0))
			if err != nil {
				t.Fatalf("Render: %v", err)
			}

			gotNames := make([]string, 0, len(files))
			for name := range files {
				gotNames = append(gotNames, name)
			}
			sort.Strings(gotNames)
			if !slices.Equal(gotNames, wantNames) {
				t.Fatalf("rendered filenames = %v, want %v", gotNames, wantNames)
			}

			for _, name := range wantNames {
				compareGolden(t, string(server)+"/set/"+name, files[name])
			}

			for _, name := range wantNames {
				if name == "_maintenance.html" {
					if !bytes.HasPrefix(files[name], []byte("<!-- Generated by devstack. Do not edit. -->\n")) {
						t.Errorf("%s does not start with the generated HTML header", name)
					}
					continue
				}
				if !bytes.HasPrefix(files[name], []byte("# Generated by devstack. Do not edit.\n")) {
					t.Errorf("%s does not start with the generated config header", name)
				}
			}
		})
	}
}

func TestRenderSetDoesNotEmbedCertificateMaterial(t *testing.T) {
	markers := []string{
		"CERTIFICATE-PRIVATE-MARKER",
		"KEY-PRIVATE-MARKER",
		"DASHBOARD-CERT-MARKER",
		"DASHBOARD-KEY-MARKER",
	}
	for _, server := range []Server{ServerNginx, ServerApache} {
		t.Run(string(server), func(t *testing.T) {
			set := testSet(server, 0)
			set.Sites[0].CertPEM = []byte(markers[0])
			set.Sites[0].KeyPEM = []byte(markers[1])
			set.Dashboard.CertPEM = []byte(markers[2])
			set.Dashboard.KeyPEM = []byte(markers[3])

			files, err := Render(set)
			if err != nil {
				t.Fatalf("Render: %v", err)
			}
			for name, data := range files {
				for _, marker := range markers {
					if bytes.Contains(data, []byte(marker)) {
						t.Errorf("%s embeds certificate material %q", name, marker)
					}
				}
			}
		})
	}
}

