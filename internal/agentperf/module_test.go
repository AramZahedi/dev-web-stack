package agentperf_test

import (
	"context"
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"

	"github.com/AramZahedi/dev-web-stack/internal/agentperf"
	"github.com/AramZahedi/dev-web-stack/internal/agentproto"
)

type fakeRunner struct {
	calls [][]string
	err   error
}

func (r *fakeRunner) Run(_ context.Context, name string, args ...string) ([]byte, error) {
	r.calls = append(r.calls, append([]string{name}, args...))
	return nil, r.err
}

func hostRequest() agentproto.PerformanceApplyRequest {
	return agentproto.PerformanceApplyRequest{
		Profile: "balanced",
		Host: agentproto.PerformanceHostValues{
			FileMax: 1 << 20, Somaxconn: 4096, NetdevMaxBacklog: 4096,
			IPLocalPortMin: 32768, IPLocalPortMax: 60999,
			NoFileSoft: 65536, NoFileHard: 1 << 20,
		},
	}
}

func newModule(t *testing.T) (*agentperf.Module, string, string, string, *fakeRunner) {
	t.Helper()
	root := t.TempDir()
	sysctl := filepath.Join(root, "etc", "sysctl.d", "99-devstack-performance.conf")
	limits := filepath.Join(root, "etc", "security", "limits.d", "99-devstack-performance.conf")
	proc := filepath.Join(root, "proc", "sys")
	for rel, value := range map[string]string{
		"net/core/somaxconn":           "4096\n",
		"net/core/netdev_max_backlog":  "4096\n",
		"fs/file-max":                  "1048576\n",
		"net/ipv4/ip_local_port_range": "32768\t60999\n",
	} {
		path := filepath.Join(proc, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(value), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	runner := &fakeRunner{}
	module, err := agentperf.New(agentperf.Config{
		Root: root, SysctlPath: sysctl, LimitsPath: limits, ProcRoot: proc,
		Runner: runner,
		Now: func() time.Time {
			return time.Date(2026, 11, 3, 12, 0, 0, 0, time.UTC)
		},
	})
	if err != nil {
		t.Fatal(err)
	}
	return module, sysctl, limits, root, runner
}

func TestApplyWritesFilesRefreshesAndVerifies(t *testing.T) {
	module, sysctl, limits, _, runner := newModule(t)
	resp, err := module.Apply(context.Background(), hostRequest())
	if err != nil {
		t.Fatalf("Apply: %v", err)
	}
	if !resp.Applied || len(resp.Targets) != 1 || !resp.Targets[0].Applied {
		t.Fatalf("apply response = %+v", resp)
	}
	for _, path := range []string{sysctl, limits} {
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("read %s: %v", path, err)
		}
		if !strings.Contains(string(data), "Code generated by devstack performance profile") {
			t.Fatalf("%s missing generated header: %s", path, data)
		}
	}
	if len(runner.calls) != 1 || strings.Join(runner.calls[0], " ") != "sysctl --system" {
		t.Fatalf("runner calls = %v", runner.calls)
	}
	status, err := module.Status()
	if err != nil {
		t.Fatal(err)
	}
	if len(status.Targets) != 1 || !status.Targets[0].Applied || status.Targets[0].Target != "wsl" {
		t.Fatalf("status = %+v", status)
	}
}

func TestApplyVerificationFailureRollsBack(t *testing.T) {
	module, sysctl, limits, root, _ := newModule(t)
	if err := os.WriteFile(filepath.Join(root, "proc", "sys", "net", "core", "somaxconn"), []byte("1\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := module.Apply(context.Background(), hostRequest()); err == nil {
		t.Fatal("Apply succeeded despite verification failure")
	}
	for _, path := range []string{sysctl, limits} {
		if _, err := os.Stat(path); !os.IsNotExist(err) {
			t.Fatalf("rollback left %s: %v", path, err)
		}
	}
}

func TestResetRestoresPriorFiles(t *testing.T) {
	module, sysctl, limits, _, _ := newModule(t)
	priorSysctl := "# prior sysctl\n"
	priorLimits := "# prior limits\n"
	if err := os.MkdirAll(filepath.Dir(sysctl), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Dir(limits), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(sysctl, []byte(priorSysctl), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(limits, []byte(priorLimits), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := module.Apply(context.Background(), hostRequest()); err != nil {
		t.Fatal(err)
	}
	resp, err := module.Reset(context.Background())
	if err != nil {
		t.Fatalf("Reset: %v", err)
	}
	if !resp.Restored {
		t.Fatal("reset did not report restored")
	}
	for path, want := range map[string]string{sysctl: priorSysctl, limits: priorLimits} {
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		if string(data) != want {
			t.Fatalf("%s = %q, want %q", path, data, want)
		}
	}
}
