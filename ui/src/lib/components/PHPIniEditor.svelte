<script lang="ts">
  import { tick } from 'svelte';
  import { CircleAlert, Plus, Trash2 } from 'lucide-svelte';
  import { describePHPError, type PHPErrorDescription } from '../errors';
  import type { PHPChange } from '../types';
  import Button from './Button.svelte';
  import Field from './Field.svelte';

  interface Props {
    ini: Record<string, string>;
    raw: string;
    generated: string;
    onApply: (change: PHPChange) => Promise<void>;
    disabled?: boolean;
  }

  let { ini, raw, generated, onApply, disabled = false }: Props = $props();

  interface Row {
    id: number;
    key: string;
    value: string;
  }

  let rows = $state<Row[]>([]);
  let rawText = $state('');
  let syncedIni: Record<string, string> | null = null;
  let syncedRaw: string | null = null;
  let rowSeq = 0;
  let busy = $state(false);
  let error = $state<PHPErrorDescription | null>(null);

  $effect(() => {
    if (syncedIni !== ini) {
      syncedIni = ini;
      rows = Object.entries(ini).map(([key, value]) => ({ id: ++rowSeq, key, value }));
    }
    if (syncedRaw !== raw) {
      syncedRaw = raw;
      rawText = raw;
    }
  });

  function addRow(): void {
    rows = [...rows, { id: ++rowSeq, key: '', value: '' }];
    void tick().then(() => {
      document.getElementById(`ini-key-${rows[rows.length - 1]?.id}`)?.focus();
    });
  }

  function removeRow(id: number): void {
    rows = rows.filter((row) => row.id !== id);
  }

  function buildIni(): Record<string, string> | null {
    const result: Record<string, string> = {};
    for (const row of rows) {
      const key = row.key.trim();
      if (!key) {
        if (row.value.trim()) {
          error = {
            code: 'PHP_CONFIG_INVALID',
            message: 'Add a directive name for this value before applying.',
          };
          return null;
        }
        continue;
      }
      if (key in result) {
        error = {
          code: 'PHP_CONFIG_INVALID',
          message: `The directive “${key}” is defined more than once.`,
        };
        return null;
      }
      result[key] = row.value;
    }
    return result;
  }

  async function apply(): Promise<void> {
    if (busy || disabled) return;
    error = null;
    const values = buildIni();
    if (!values) return;
    busy = true;
    try {
      await onApply({ ini: values, ini_raw: rawText });
    } catch (caught) {
      error = describePHPError(caught);
    } finally {
      busy = false;
    }
  }
</script>

<div class="ini-editor">
  <div class="section-head">
    <div>
      <h3>Directives</h3>
      <p>Per-site overrides. Remove every row to fall back to the PHP version defaults.</p>
    </div>
    <Button size="sm" variant="ghost" onclick={addRow} disabled={disabled || busy}>
      <Plus size={13} strokeWidth={2.2} aria-hidden="true" />
      Add directive
    </Button>
  </div>

  {#if rows.length === 0}
    <p class="empty">No per-site directives. The version defaults apply.</p>
  {:else}
    <div class="rows" role="list" aria-label="PHP ini directives">
      {#each rows as row, index (row.id)}
        <div class="row" role="listitem">
          <label class="sr-only" for={`ini-key-${row.id}`}>Directive {index + 1} name</label>
          <input
            id={`ini-key-${row.id}`}
            class="input mono key"
            type="text"
            placeholder="memory_limit"
            autocomplete="off"
            spellcheck="false"
            bind:value={row.key}
            aria-label={`${row.key || `Directive ${index + 1}`} name`}
            disabled={disabled || busy}
          />
          <span class="equals mono" aria-hidden="true">=</span>
          <label class="sr-only" for={`ini-value-${row.id}`}>{row.key || `Directive ${index + 1}`} value</label>
          <input
            id={`ini-value-${row.id}`}
            class="input mono value"
            type="text"
            placeholder="256M"
            autocomplete="off"
            spellcheck="false"
            bind:value={row.value}
            aria-label={`${row.key || `Directive ${index + 1}`} value`}
            disabled={disabled || busy}
          />
          <button
            type="button"
            class="remove"
            aria-label={`Remove ${row.key || `directive ${index + 1}`}`}
            disabled={disabled || busy}
            onclick={() => removeRow(row.id)}
          >
            <Trash2 size={14} strokeWidth={1.9} aria-hidden="true" />
          </button>
        </div>
      {/each}
    </div>
  {/if}

  <Field
    id="php-ini-raw"
    label="Site php.ini section"
    hint="Appended as raw directives for this site only. The managed extension block is generated by devstack and cannot be edited here."
  >
    <textarea
      id="php-ini-raw"
      class="input mono raw"
      rows="6"
      spellcheck="false"
      bind:value={rawText}
      disabled={disabled || busy}
      aria-describedby="php-ini-raw-hint"
    ></textarea>
  </Field>

  <div class="preview-block">
    <div class="preview-head">
      <h3>Generated preview</h3>
      <span class="read-only">Read-only</span>
    </div>
    <p class="preview-copy">
      The managed extension block below is rendered by devstack. Applying saves only the
      directives and raw site section above.
    </p>
    <!-- The preview scrolls independently; it is labelled and read-only. -->
    <!-- svelte-ignore a11y_no_noninteractive_tabindex -->
    <pre aria-label="Generated php.ini preview" tabindex="0">{generated}</pre>
  </div>

  {#if error}
    <div class="php-error" role="alert">
      <div class="error-title">
        <CircleAlert size={14} strokeWidth={2} aria-hidden="true" />
        <span class="code mono">{error.code}</span>
        <span>{error.message}</span>
      </div>
      {#if error.details?.message}
        <p class="detail">{error.details.message}</p>
      {/if}
      {#if error.details?.line !== undefined && error.details.line > 0}
        <p class="detail">Line {error.details.line}</p>
      {/if}
      {#if error.details?.field}
        <p class="detail">Field <span class="mono">{error.details.field}</span></p>
      {/if}
      {#if error.details?.output}
        <pre class="output" aria-label="PHP validation output">{error.details.output}</pre>
      {/if}
    </div>
  {/if}

  <div class="actions">
    <Button
      variant="primary"
      size="sm"
      onclick={apply}
      loading={busy}
      disabled={disabled || busy}
    >
      {busy ? 'Applying…' : 'Apply PHP settings'}
    </Button>
  </div>
</div>

