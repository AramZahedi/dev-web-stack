#!/usr/bin/env bash
# Build one relocatable PHP linux-x64 artifact from the pinned source and PECL
# tarballs in extensions.lock. The archive layout is
#
#   php-<version>-r<revision>-linux-x64/
#     bin/php  sbin/php-fpm  etc/php.ini  lib/php/extensions/*.so  lib/*.so
#
# and every ELF file gets an $ORIGIN-relative RPATH so the tree can be extracted
# anywhere. This command performs a real source build and is intended for CI or
# a machine with the documented build dependencies.
set -euo pipefail
IFS=$'\n\t'
export LC_ALL=C

# The release artifact targets glibc 2.35 (Ubuntu 22.04). A newer build host
# can link symbols that are unavailable on the oldest supported platform.
if command -v ldd >/dev/null 2>&1; then
	host_glibc="$(ldd --version 2>/dev/null | head -n 1 | awk '{print $NF}')"
	if [[ $host_glibc =~ ^[0-9]+\.[0-9]+$ ]] &&
		[[ $(printf '%s\n' 2.35 "$host_glibc" | sort -V | tail -n 1) == "$host_glibc" ]] &&
		[[ $host_glibc != 2.35 ]]; then
		printf 'build.sh: warning: host glibc %s is newer than the 2.35 release baseline; the artifact may not run on Ubuntu 22.04\n' "$host_glibc" >&2
	fi
fi

script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
readonly script_dir
repo_root=$(cd -- "$script_dir/../.." && pwd)
readonly repo_root
readonly lock_file="${PHP_LOCK_FILE:-$script_dir/extensions.lock}"
readonly manifest="$repo_root/internal/catalog/php.json"
readonly base_ini="$script_dir/base-php.ini"
# Keep in sync with update-lock.sh. imap is documented as blocked in README.md.
# igbinary is first so its headers exist before redis and memcached are
# configured with igbinary serializer support.
readonly pecl_packages=(igbinary redis apcu xdebug imagick memcached ssh2 yaml msgpack grpc pcov)

line=''
version=''
revision=''
output="$repo_root/dist/php"

usage() {
	cat <<'EOF'
usage: build.sh --line <8.2|8.3|8.4|8.5> --revision <n> [--version <x.y.z>] [--output <dir>]

Builds php-<version>-r<revision>-linux-x64.tar.gz from the source pinned in
extensions.lock and the verified PECL extras. --version defaults to the locked
patch version and must match the lock when supplied. The command refuses to run
as root and requires the build dependencies listed in build/php/README.md.
EOF
}

die() {
	printf 'build.sh: %s\n' "$*" >&2
	exit 1
}

note() {
	printf '==> %s\n' "$*"
}

while [[ $# -gt 0 ]]; do
	case "$1" in
	--line)
		[[ $# -ge 2 ]] || die '--line requires a value'
		line=$2
		shift 2
		;;
	--version)
		[[ $# -ge 2 ]] || die '--version requires a value'
		version=$2
		shift 2
		;;
	--revision)
		[[ $# -ge 2 ]] || die '--revision requires a value'
		revision=$2
		shift 2
		;;
	--output)
		[[ $# -ge 2 ]] || die '--output requires a directory'
		output=$2
		shift 2
		;;
	-h | --help)
		usage
		exit 0
		;;
	*)
		die "unknown argument '$1'"
		;;
	esac
done

[[ -n $line ]] || die '--line is required'
case "$line" in
8.2 | 8.3 | 8.4 | 8.5) ;;
*) die "unsupported PHP line '$line' (want 8.2, 8.3, 8.4, or 8.5)" ;;
esac
[[ $revision =~ ^[1-9][0-9]*$ ]] || die "--revision '$revision' must be a positive integer"

if [[ $(id -u) -eq 0 ]]; then
	die 'refusing to run as root; run the build as your normal user (the prefix is staged in a temporary directory)'
fi

[[ -f $lock_file ]] || die "lock file $lock_file is missing; run build/php/update-lock.sh"
[[ -f $manifest ]] || die "PHP extension manifest $manifest is missing"
[[ -f $base_ini ]] || die "base php.ini $base_ini is missing"

# The lock is committed, sorted KEY=value data generated by update-lock.sh.
# shellcheck disable=SC1090
source "$lock_file"
line_key=${line//./_}
version_var="PHP_${line_key}_VERSION"
sha_var="PHP_${line_key}_SHA256"
locked_version="${!version_var:-}"
locked_sha="${!sha_var:-}"
if [[ -z $locked_version || ! $locked_sha =~ ^[0-9a-f]{64}$ ]]; then
	die "PHP $line is not pinned in $lock_file (need $version_var and $sha_var); run build/php/update-lock.sh"
fi
if [[ -n $version && $version != "$locked_version" ]]; then
	die "--version $version does not match $version_var=$locked_version; update the lock deliberately or omit --version"
fi
version=$locked_version
[[ $version =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "locked PHP version '$version' is not x.y.z"
[[ $version == "$line".* ]] || die "locked PHP version $version does not belong to line $line"

# Fail before any download or compilation when an extra is not pinned.
for package in "${pecl_packages[@]}"; do
	package_key=$(printf '%s' "$package" | tr '[:lower:]' '[:upper:]')
	package_version_var="PECL_${package_key}_VERSION"
	package_sha_var="PECL_${package_key}_SHA256"
	if [[ -z ${!package_version_var:-} || ! ${!package_sha_var:-} =~ ^[0-9a-f]{64}$ ]]; then
		die "PECL package $package is not pinned in $lock_file; run build/php/update-lock.sh to verify and add it"
	fi
done

for tool in awk curl file gcc gzip jq ldd make patchelf perl pkg-config sha256sum tar xz; do
	command -v "$tool" >/dev/null 2>&1 ||
		die "required build tool '$tool' is missing; install the dependencies listed in build/php/README.md"
done
command -v autoconf >/dev/null 2>&1 ||
	die "required build tool 'autoconf' is missing; install the dependencies listed in build/php/README.md"
if ! pkg-config --exists oniguruma libsodium; then
	die 'pkg-config cannot find both oniguruma and libsodium; install libonig-dev and libsodium-dev (see build/php/README.md)'
fi

mkdir -p -- "$output"
output=$(cd -- "$output" && pwd)
if [[ -n ${PHP_SOURCE_CACHE:-} ]]; then
	cache_dir=$PHP_SOURCE_CACHE
elif [[ -n ${XDG_CACHE_HOME:-} ]]; then
	cache_dir=$XDG_CACHE_HOME/devstack/php-sources
elif [[ -n ${HOME:-} ]]; then
	cache_dir=$HOME/.cache/devstack/php-sources
else
	cache_dir=$script_dir/.cache/php-sources
fi
mkdir -p -- "$cache_dir"

package_name="php-$version-r$revision-linux-x64"
work=$(mktemp -d "${TMPDIR:-/tmp}/devstack-php-build-XXXXXX") ||
	die 'could not create a temporary build directory'
package_dir="$work/$package_name"
if [[ -n ${PHP_JOBS:-} ]]; then
	jobs=$PHP_JOBS
else
	jobs=$(nproc 2>/dev/null || getconf _NPROCESSORS_ONLN 2>/dev/null || echo 2)
fi
[[ $jobs =~ ^[1-9][0-9]*$ ]] || die "PHP_JOBS '$jobs' is not a positive integer"
log_dir="$work/logs"
mkdir -p "$log_dir"

cleanup() {
	local status=$?
	if [[ $status -ne 0 ]]; then
		printf 'build.sh: work directory kept for inspection: %s\n' "$work" >&2
	else
		rm -rf -- "$work"
	fi
}
trap cleanup EXIT

download_verified() {
	local url=$1 destination=$2 expected=$3 label=$4 temporary actual
	if [[ -f $destination ]]; then
		actual=$(sha256sum "$destination" | awk '{print $1}')
		if [[ $actual == "$expected" ]]; then
			return 0
		fi
		rm -f -- "$destination"
	fi
	temporary=$(mktemp "${destination}.tmp.XXXXXX")
	if ! curl -fsSL --retry 3 --connect-timeout 20 --max-time 600 -o "$temporary" "$url"; then
		rm -f -- "$temporary"
		die "could not download $label from $url"
	fi
	actual=$(sha256sum "$temporary" | awk '{print $1}')
	if [[ $actual != "$expected" ]]; then
		rm -f -- "$temporary"
		die "$label checksum mismatch: expected $expected, got $actual"
	fi
	mv -- "$temporary" "$destination"
}

run_logged() {
	local label=$1 log=$2
	shift 2
	if ! "$@" >"$log" 2>&1; then
		printf 'build.sh: %s failed; last 100 lines of %s:\n' "$label" "$log" >&2
		tail -n 100 "$log" >&2
		exit 1
	fi
}

source_archive="$cache_dir/php-$version.tar.xz"
note "downloading PHP $version source"
download_verified "https://www.php.net/distributions/php-$version.tar.xz" \
	"$source_archive" "$locked_sha" "PHP $version source"
tar -xJf "$source_archive" -C "$work"
source_dir="$work/php-$version"
[[ -d $source_dir ]] || die "source archive did not contain php-$version"

mapfile -t standard_so < <(jq -r --arg line "$line" '
	(.builtin_by_version[$line] // []) as $builtins
	| .extensions[]
	| select(.standard == true)
	| select(.name != "imap")
	| select((.versions // []) | index($line))
	| .name as $name
	| select(($builtins | index($name)) == null)
	| .so
' "$manifest")
[[ ${#standard_so[@]} -gt 0 ]] || die "no standard extensions found for PHP $line in $manifest"

mkdir -p -- "$package_dir"
# Keep the relocatable build hardened even when the host toolchain does not
# inject these flags by default. PIE remains the distribution default.
export CFLAGS="${CFLAGS:-} -O2 -fstack-protector-strong -U_FORTIFY_SOURCE -D_FORTIFY_SOURCE=2"
export CPPFLAGS="${CPPFLAGS:-} -D_FORTIFY_SOURCE=2"
export LDFLAGS="${LDFLAGS:-} -Wl,-z,relro,-z,now"
configure_args=(
	"--prefix=$package_dir"
	--enable-fpm
	--disable-cgi
	--without-pear
	--with-pic
	--with-libxml
	--with-openssl=shared
	--with-zlib=shared
	--with-curl=shared
	--enable-mbstring=shared
	--enable-intl=shared
	--enable-sockets=shared
	--enable-soap=shared
	# PHP's configure option is --with-zip (there is no --enable-zip).
	--with-zip=shared
	--enable-pdo=shared
	"--with-pdo-mysql=shared,mysqlnd"
	--with-pdo-pgsql=shared
	--with-pdo-sqlite=shared
	--with-pgsql=shared
	"--with-mysqli=shared,mysqlnd"
	--enable-gd=shared
	--with-freetype
	--with-jpeg
	--with-webp
	--enable-bcmath=shared
	--with-bz2=shared
	--enable-calendar=shared
	--enable-dba=shared
	--with-gdbm=/usr
	--enable-exif=shared
	--with-ffi=shared
	--enable-fileinfo=shared
	--enable-ftp=shared
	--with-gettext=shared
	--with-gmp=shared
	--with-iconv=shared
	--with-ldap=shared
	--enable-pcntl=shared
	--enable-posix=shared
	--with-readline=shared
	--enable-session=shared
	--enable-simplexml=shared
	--with-sodium=shared
	--with-sqlite3=shared
	--enable-sysvmsg=shared
	--enable-sysvsem=shared
	--enable-sysvshm=shared
	--with-tidy=shared
	--enable-tokenizer=shared
	--enable-xml=shared
	--enable-xmlreader=shared
	--enable-xmlwriter=shared
	--enable-dom=shared
	--with-xsl=shared
	--enable-phar=shared
)
# PHP 8.5 always builds OPcache into the binary and no longer produces
# opcache.so; the configure flag was removed. Other lines keep it shared.
if [[ $line != '8.5' ]]; then
	configure_args+=(--enable-opcache=shared)
fi

note "configuring PHP $version"
(
	cd "$source_dir"
	./configure "${configure_args[@]}"
) >"$log_dir/php-configure.log" 2>&1 ||
	{
		printf 'build.sh: PHP configure failed; last 100 lines of %s:\n' "$log_dir/php-configure.log" >&2
		tail -n 100 "$log_dir/php-configure.log" >&2
		exit 1
	}

note "building PHP $version with $jobs jobs"
run_logged 'PHP make' "$log_dir/php-make.log" make -C "$source_dir" -j"$jobs"
run_logged 'PHP make install' "$log_dir/php-install.log" make -C "$source_dir" install

[[ -x "$package_dir/bin/php" ]] || die "install did not produce $package_dir/bin/php"
[[ -x "$package_dir/sbin/php-fpm" ]] || die "install did not produce $package_dir/sbin/php-fpm"
"$package_dir/bin/php" -n -v >/dev/null || die 'the installed php CLI does not run'
"$package_dir/sbin/php-fpm" -n -v >/dev/null || die 'the installed php-fpm does not run'

ext_dir="$package_dir/lib/php/extensions"
mkdir -p -- "$ext_dir"

for package in "${pecl_packages[@]}"; do
	package_key=$(printf '%s' "$package" | tr '[:lower:]' '[:upper:]')
	package_version_var="PECL_${package_key}_VERSION"
	package_sha_var="PECL_${package_key}_SHA256"
	package_version="${!package_version_var:-}"
	package_sha="${!package_sha_var:-}"
	if [[ -z $package_version || ! $package_sha =~ ^[0-9a-f]{64}$ ]]; then
		die "PECL package $package is not pinned in $lock_file; run build/php/update-lock.sh to verify and add it"
	fi
	package_archive="$cache_dir/$package-$package_version.tgz"
	note "downloading PECL $package $package_version"
	download_verified "https://pecl.php.net/get/$package-$package_version.tgz" \
		"$package_archive" "$package_sha" "PECL $package $package_version"
	mkdir -p "$work/pecl"
	tar -xzf "$package_archive" -C "$work/pecl"
	package_src="$work/pecl/$package-$package_version"
	[[ -d $package_src ]] || die "PECL archive $package-$package_version did not contain $package_src"
	pecl_configure=(--with-php-config="$package_dir/bin/php-config")
	case "$package" in
	redis)
		pecl_configure+=(--enable-redis-igbinary)
		;;
	memcached)
		pecl_configure+=(--with-libmemcached-dir=/usr --enable-memcached-igbinary --disable-memcached-sasl)
		;;
	imagick)
		pecl_configure+=(--with-imagick=/usr)
		;;
	esac
	(
		cd "$package_src"
		"$package_dir/bin/phpize"
		./configure "${pecl_configure[@]}"
		make -j"$jobs"
		make install
	) >"$log_dir/pecl-$package.log" 2>&1 ||
		{
			printf 'build.sh: PECL %s failed; last 100 lines of %s:\n' "$package" "$log_dir/pecl-$package.log" >&2
			tail -n 100 "$log_dir/pecl-$package.log" >&2
			exit 1
		}
done

# PHP installs shared modules under an API-versioned directory. devstack sets
# extension_dir explicitly, so flatten the tree into lib/php/extensions.
find "$package_dir/lib/php/extensions" -mindepth 2 -maxdepth 2 -type f -name '*.so' \
	-exec cp -p {} "$ext_dir"/ \;
find "$ext_dir" -mindepth 1 -maxdepth 1 -type d -exec rm -rf {} +

expected_so=("${standard_so[@]}")
for package in "${pecl_packages[@]}"; do
	expected_so+=("$package.so")
done
missing=()
for so in "${expected_so[@]}"; do
	[[ -f "$ext_dir/$so" ]] || missing+=("$so")
done
if [[ ${#missing[@]} -gt 0 ]]; then
	die "the build did not produce expected shared extensions: ${missing[*]}"
fi

# Bundle non-glibc shared libraries and their transitive dependencies. glibc
# itself (and the dynamic loader) stays a host baseline (glibc 2.35 on the
# ubuntu-22.04 build runner).
note 'bundling shared libraries'
for _ in $(seq 1 10); do
	before=$(find "$package_dir/lib" -maxdepth 1 -type f -name 'lib*.so*' | wc -l)
	for target in "$package_dir"/bin/* "$package_dir"/sbin/* "$ext_dir"/*.so "$package_dir"/lib/lib*.so*; do
		[[ -f $target ]] || continue
		file -b "$target" | grep -q '^ELF' || continue
		while IFS= read -r library; do
			[[ -n $library ]] || continue
			base=$(basename "$library")
			case "$base" in
			linux-vdso.so.* | ld-linux* | libc.so.* | libm.so.* | libpthread.so.* | libdl.so.* | librt.so.* | libresolv.so.* | libutil.so.* | libnsl.so.*)
				continue
				;;
			esac
			[[ $library == "$package_dir"/* ]] && continue
			[[ -f "$package_dir/lib/$base" ]] && continue
			cp -L --preserve=mode "$library" "$package_dir/lib/$base"
		done < <(ldd "$target" 2>/dev/null | awk '{ if ($2 == "=>" && $3 ~ /^\//) print $3; else if ($1 ~ /^\//) print $1 }')
	done
	after=$(find "$package_dir/lib" -maxdepth 1 -type f -name 'lib*.so*' | wc -l)
	[[ $before -eq $after ]] && break
done

note 'setting relative RPATHs'
for target in "$package_dir"/bin/* "$package_dir"/sbin/*; do
	[[ -f $target ]] || continue
	file -b "$target" | grep -q '^ELF' || continue
	# shellcheck disable=SC2016 # $ORIGIN is a literal ELF RPATH token.
	patchelf --set-rpath '$ORIGIN/../lib' "$target"
done
for target in "$ext_dir"/*.so; do
	[[ -f $target ]] || continue
	# $ORIGIN/../.. is the real prefix/lib path; the second entry keeps the
	# documented $ORIGIN/../lib value for callers that expect it.
	# shellcheck disable=SC2016 # $ORIGIN is a literal ELF RPATH token.
	patchelf --set-rpath '$ORIGIN/../..:$ORIGIN/../lib' "$target"
done
for target in "$package_dir"/lib/lib*.so*; do
	[[ -f $target ]] || continue
	file -b "$target" | grep -q '^ELF' || continue
	# shellcheck disable=SC2016 # $ORIGIN is a literal ELF RPATH token.
	patchelf --set-rpath '$ORIGIN' "$target"
done

for target in "$package_dir"/bin/* "$package_dir"/sbin/* "$ext_dir"/*.so "$package_dir"/lib/lib*.so*; do
	[[ -f $target ]] || continue
	file -b "$target" | grep -q '^ELF' || continue
	if ldd "$target" 2>/dev/null | grep -q 'not found'; then
		printf 'build.sh: unresolved shared libraries in %s:\n' "$target" >&2
		ldd "$target" | grep 'not found' >&2 || true
		die "unresolved shared library dependencies"
	fi
done

mkdir -p "$package_dir/etc"
install -m 0644 "$base_ini" "$package_dir/etc/php.ini"
if [[ -f "$source_dir/LICENSE" ]]; then
	install -m 0644 "$source_dir/LICENSE" "$package_dir/LICENSE"
fi

archive="$output/$package_name.tar.gz"
temporary=$(mktemp "${archive}.tmp.XXXXXX")
tar --sort=name --mtime="@${SOURCE_DATE_EPOCH:-0}" --owner=0 --group=0 --numeric-owner \
	-C "$work" -cf - "$package_name" | gzip -9n >"$temporary"
chmod 0644 "$temporary"
mv -- "$temporary" "$archive"

note "built $archive"
printf 'sha256: %s\n' "$(sha256sum "$archive" | awk '{print $1}')"
printf 'size: %s\n' "$(stat -c '%s' "$archive")"
