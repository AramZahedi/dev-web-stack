// Command catalogmerge merges the PHP catalog artifact produced by
// .github/workflows/php.yml into a devstack catalog document.
//
// Every incoming PHP entry is validated before anything is written: it must be
// a linux-x64 PHP build for revision 1 or newer, use HTTPS, carry a lowercase
// SHA-256 and a positive size, and point at the exact archive name for its
// version and revision. The merge replaces all existing PHP entries with the
// validated set (sorted by version, then revision) and preserves every non-PHP
// entry in its existing order. The output is written atomically and --check
// validates without writing.
//
// The production catalog stays Node-only until real 8.2-8.5 artifacts have
// been published with checksums; this command is the gated release step that
// adds them.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"net/url"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/AramZahedi/dev-web-stack/internal/catalog"
)

var (
	versionPattern  = regexp.MustCompile(`^[0-9]+\.[0-9]+\.[0-9]+$`)
	checksumPattern = regexp.MustCompile(`^[0-9a-f]{64}$`)

	// requiredPHPLines are the supported PHP lines. A release merge must carry
	// at least one checksummed build for each of them.
	requiredPHPLines = []string{"8.2", "8.3", "8.4", "8.5"}
)

// Options describes one catalog merge. Catalog is the current catalog document
// and PHPCatalog is the php-catalog.json artifact generated by the PHP
// workflow. Output defaults to Catalog, which updates the catalog in place.
type Options struct {
	Catalog    string
	PHPCatalog string
	Output     string
	Check      bool
}

// mergeCatalogs validates the incoming PHP document and returns a catalog with
// every existing PHP entry replaced by the incoming set. Non-PHP entries keep
// their current relative order.
func mergeCatalogs(current, incoming catalog.Catalog) (catalog.Catalog, error) {
	phpEntries, err := validatePHPCatalog(incoming)
	if err != nil {
		return catalog.Catalog{}, err
	}

	merged := make([]catalog.Entry, 0, len(current.Entries)+len(phpEntries))
	for _, entry := range current.Entries {
		if entry.Kind == "php" {
			continue
		}
		merged = append(merged, entry)
	}
	merged = append(merged, phpEntries...)
	return catalog.Catalog{Entries: merged}, nil
}

// validatePHPCatalog validates every incoming entry, rejects duplicate IDs, and
// requires at least one build for each supported PHP line. The returned entries
// are sorted by version and then revision.
func validatePHPCatalog(document catalog.Catalog) ([]catalog.Entry, error) {
	if len(document.Entries) == 0 {
		return nil, errors.New("the PHP catalog has no entries")
	}

	seenIDs := make(map[string]struct{}, len(document.Entries))
	seenLines := make(map[string]struct{}, len(requiredPHPLines))
	entries := make([]catalog.Entry, 0, len(document.Entries))
	for i, entry := range document.Entries {
		if err := validatePHPEntry(entry); err != nil {
			return nil, fmt.Errorf("entry %d (%q): %w", i, entry.ID, err)
		}
		if _, ok := seenIDs[entry.ID]; ok {
			return nil, fmt.Errorf("entry %d (%q): duplicate id", i, entry.ID)
		}
		seenIDs[entry.ID] = struct{}{}
		seenLines[catalog.LineOf(entry.Version)] = struct{}{}
		entries = append(entries, entry)
	}

	var missing []string
	for _, line := range requiredPHPLines {
		if _, ok := seenLines[line]; !ok {
			missing = append(missing, line)
		}
	}
	if len(missing) != 0 {
		return nil, fmt.Errorf(
			"missing PHP entries for line(s) %s: the catalog must contain at least one build for each of 8.2, 8.3, 8.4, and 8.5",
			strings.Join(missing, ", "),
		)
	}

	sort.SliceStable(entries, func(i, j int) bool {
		if compared := compareVersions(entries[i].Version, entries[j].Version); compared != 0 {
			return compared < 0
		}
		return entries[i].Revision < entries[j].Revision
	})
	return entries, nil
}

// validatePHPEntry enforces the catalog invariants the installer relies on,
// plus the PHP artifact naming contract.
func validatePHPEntry(entry catalog.Entry) error {
	if entry.Kind != "php" {
		return fmt.Errorf("kind must be php, got %q", entry.Kind)
	}
	if !versionPattern.MatchString(entry.Version) {
		return fmt.Errorf("invalid version %q (want x.y.z)", entry.Version)
	}
	if entry.Revision < 1 {
		return fmt.Errorf("invalid revision %d (want at least 1)", entry.Revision)
	}
	if entry.Build != "linux-x64" {
		return fmt.Errorf("invalid build %q (want linux-x64)", entry.Build)
	}
	wantID := catalog.FormatID("php", entry.Version, entry.Revision)
	if entry.ID != wantID {
		return fmt.Errorf("id %q does not match version/revision (want %q)", entry.ID, wantID)
	}
	if !checksumPattern.MatchString(entry.SHA256) {
		return fmt.Errorf("invalid sha256 %q (want 64 lowercase hex characters)", entry.SHA256)
	}
	if entry.Size <= 0 {
		return fmt.Errorf("invalid size %d (want a positive byte count)", entry.Size)
	}
	if strings.ContainsRune(entry.URL, 0) {
		return fmt.Errorf("url contains NUL")
	}

	parsed, err := url.Parse(entry.URL)
	if err != nil {
		return fmt.Errorf("invalid url %q: %w", entry.URL, err)
	}
	if parsed.Scheme != "https" {
		return fmt.Errorf("url %q must use https", entry.URL)
	}
	if parsed.Host == "" {
		return fmt.Errorf("url %q has no host", entry.URL)
	}
	if parsed.User != nil {
		return fmt.Errorf("url %q must not contain userinfo", entry.URL)
	}
	if parsed.RawQuery != "" || parsed.ForceQuery {
		return fmt.Errorf("url %q must not contain a query", entry.URL)
	}
	if parsed.Fragment != "" || strings.ContainsRune(entry.URL, '#') {
		return fmt.Errorf("url %q must not contain a fragment", entry.URL)
	}
	wantName := fmt.Sprintf("php-%s-r%d-linux-x64.tar.gz", entry.Version, entry.Revision)
	if path.Base(parsed.Path) != wantName {
		return fmt.Errorf("url basename %q does not match version/revision (want %q)", path.Base(parsed.Path), wantName)
	}
	return nil
}

// compareVersions compares dotted numeric versions component by component.
func compareVersions(a, b string) int {
	ap, bp := strings.Split(a, "."), strings.Split(b, ".")
	for i := 0; i < len(ap) || i < len(bp); i++ {
		var av, bv int
		if i < len(ap) {
			av, _ = strconv.Atoi(ap[i])
		}
		if i < len(bp) {
			bv, _ = strconv.Atoi(bp[i])
		}
		if av < bv {
			return -1
		}
		if av > bv {
			return 1
		}
	}
	return 0
}

// readCatalog loads and validates a catalog document with the same parser the
// devstack binary uses at startup. It is used for the current catalog, whose
// non-PHP entries are preserved verbatim.
func readCatalog(filename string) (catalog.Catalog, error) {
	file, err := os.Open(filename)
	if err != nil {
		return catalog.Catalog{}, fmt.Errorf("open %s: %w", filename, err)
	}
	defer func() { _ = file.Close() }()

	loaded, err := catalog.LoadFrom(file)
	if err != nil {
		return catalog.Catalog{}, fmt.Errorf("load %s: %w", filename, err)
	}
	return loaded, nil
}

// decodeCatalog decodes a catalog document without applying the binary's
// parser. The PHP document is validated field by field in validatePHPCatalog so
// the error names the exact PHP contract violation; encodeCatalog re-applies
// the full parser to the merged result before anything is written.
func decodeCatalog(filename string) (catalog.Catalog, error) {
	data, err := os.ReadFile(filename)
	if err != nil {
		return catalog.Catalog{}, fmt.Errorf("read %s: %w", filename, err)
	}
	var document catalog.Catalog
	if err := json.Unmarshal(data, &document); err != nil {
		return catalog.Catalog{}, fmt.Errorf("decode %s: %w", filename, err)
	}
	return document, nil
}

// encodeCatalog serializes the merged catalog exactly like the embedded
// production document and re-parses it with the binary's startup validator. A
// catalog that would fail at startup can therefore never be installed.
func encodeCatalog(merged catalog.Catalog) ([]byte, error) {
	data, err := json.MarshalIndent(merged, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("encode catalog: %w", err)
	}
	data = append(data, '\n')
	if _, err := catalog.LoadFrom(bytes.NewReader(data)); err != nil {
		return nil, fmt.Errorf("merged catalog failed validation: %w", err)
	}
	return data, nil
}

// writeAtomic writes data to a temporary file in the destination directory,
// fsyncs it, and renames it over path. A failure at any point leaves the old
// file (or directory) untouched.
func writeAtomic(filename string, data []byte) error {
	dir := filepath.Dir(filename)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("create output directory %s: %w", dir, err)
	}

	file, err := os.CreateTemp(dir, ".catalogmerge-*")
	if err != nil {
		return fmt.Errorf("create output file in %s: %w", dir, err)
	}
	temporary := file.Name()
	defer func() { _ = os.Remove(temporary) }()

	if _, err := file.Write(data); err != nil {
		_ = file.Close()
		return fmt.Errorf("write output file: %w", err)
	}
	if err := file.Sync(); err != nil {
		_ = file.Close()
		return fmt.Errorf("sync output file: %w", err)
	}
	if err := file.Chmod(0o644); err != nil {
		_ = file.Close()
		return fmt.Errorf("chmod output file: %w", err)
	}
	if err := file.Close(); err != nil {
		return fmt.Errorf("close output file: %w", err)
	}
	if err := os.Rename(temporary, filename); err != nil {
		return fmt.Errorf("replace output file %s: %w", filename, err)
	}

	// Make the rename durable where the filesystem supports directory fsync.
	if directory, err := os.Open(dir); err == nil {
		_ = directory.Sync()
		_ = directory.Close()
	}
	return nil
}

func run(args []string, stdout, stderr io.Writer) error {
	flags := flag.NewFlagSet("catalogmerge", flag.ContinueOnError)
	flags.SetOutput(stderr)

	var opts Options
	flags.StringVar(&opts.Catalog, "catalog", "", "current catalog document (read; default output)")
	flags.StringVar(&opts.PHPCatalog, "php-catalog", "", "php-catalog.json document generated by the PHP workflow")
	flags.StringVar(&opts.Output, "output", "", "write the merged catalog here instead of --catalog")
	flags.BoolVar(&opts.Check, "check", false, "validate the merge without writing anything")
	flags.Usage = func() {
		fmt.Fprintf(stderr, "usage: catalogmerge --catalog <path> --php-catalog <path> [--output <path>] [--check]\n\n")
		flags.PrintDefaults()
	}
	if err := flags.Parse(args); err != nil {
		return err
	}
	if flags.NArg() != 0 {
		return fmt.Errorf("unexpected arguments: %s", strings.Join(flags.Args(), " "))
	}
	if opts.Catalog == "" {
		return errors.New("--catalog is required")
	}
	if opts.PHPCatalog == "" {
		return errors.New("--php-catalog is required")
	}

	output := opts.Output
	if output == "" {
		output = opts.Catalog
	}

	current, err := readCatalog(opts.Catalog)
	if err != nil {
		return err
	}
	incoming, err := decodeCatalog(opts.PHPCatalog)
	if err != nil {
		return err
	}
	merged, err := mergeCatalogs(current, incoming)
	if err != nil {
		return err
	}
	data, err := encodeCatalog(merged)
	if err != nil {
		return err
	}

	preserved := len(merged.Entries) - len(incoming.Entries)
	if opts.Check {
		if _, err := fmt.Fprintf(
			stdout,
			"catalogmerge: check ok: %d non-PHP entries preserved, %d PHP entries validated for lines %s\n",
			preserved,
			len(incoming.Entries),
			strings.Join(requiredPHPLines, ", "),
		); err != nil {
			return fmt.Errorf("print check result: %w", err)
		}
		return nil
	}

	if err := writeAtomic(output, data); err != nil {
		return err
	}
	if _, err := fmt.Fprintf(
		stdout,
		"catalogmerge: wrote %s: %d non-PHP entries preserved, %d PHP entries merged\n",
		output,
		preserved,
		len(incoming.Entries),
	); err != nil {
		return fmt.Errorf("print result: %w", err)
	}
	return nil
}

func main() {
	if err := run(os.Args[1:], os.Stdout, os.Stderr); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return
		}
		fmt.Fprintln(os.Stderr, "catalogmerge:", err)
		os.Exit(1)
	}
}
